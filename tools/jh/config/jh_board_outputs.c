hal_status_t jh_board_config_result_init(jh_board_config_result_t *result) {
  if (result == NULL)
    return HAL_EINVAL;
  hal_status_t status = text_init(&result->target);
  if (status == HAL_OK)
    status = text_init(&result->board);
  if (status == HAL_OK)
    status = text_init(&result->output_dir);
  if (status == HAL_OK)
    status = jh_board_outputs_init(&result->outputs);
  result->changed = 0;
  if (status != HAL_OK)
    jh_board_config_result_destroy(result);
  return status;
}

