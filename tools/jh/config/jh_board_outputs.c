/* os.path.normcase on Windows: lower case and backslashes. */
static char path_char(char c) {
#ifdef _WIN32
  if (c == '/')
    return '\\';
  if (c >= 'A' && c <= 'Z')
    return (char)(c - 'A' + 'a');
#endif
  return c;
}

static bool separator(char c) {
#ifdef _WIN32
  return c == '/' || c == '\\';
#else
  return c == '/';
#endif
}

/* Whether path equals root or lies below it, comparing as normcase does. */
static bool path_within(jb_json_span_t path, jb_json_span_t root) {
  while (root.length > 1 && separator(root.data[root.length - 1]))
    --root.length;
  if (path.length < root.length)
    return false;
  for (size_t i = 0; i < root.length; ++i)
    if (path_char(path.data[i]) != path_char(root.data[i]))
      return false;
  return path.length == root.length || separator(path.data[root.length]) ||
         separator(root.data[root.length - 1]);
}

/* ".build" in Path(path).parts. */
static bool has_build_component(jb_json_span_t path) {
  size_t start = 0;
  for (size_t i = 0; i <= path.length; ++i) {
    if (i < path.length && !separator(path.data[i]))
      continue;
    if (i - start == 6 && memcmp(path.data + start, ".build", 6) == 0)
      return true;
    start = i + 1;
  }
  return false;
}

hal_status_t jh_board_managed_output(const char *output_dir,
                                     const char *output_root,
                                     const char *repository_root,
                                     jb_string_t *out, jh_failure_t *failure) {
  if (output_dir == NULL || repository_root == NULL || out == NULL)
    return jh_fail_arguments(failure);
  jb_string_t managed = {0}, joined = {0}, host = {0};
  hal_status_t status = jh_fail_storage(failure, text_init(&managed));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, text_init(&joined));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, text_init(&host));
  if (status == HAL_OK)
    status = jh_python_resolve(output_dir, NULL, out, failure);
  if (status == HAL_OK && output_root != NULL)
    status = jh_python_resolve(output_root, NULL, &managed, failure);
  else if (status == HAL_OK)
    status = jh_fail_storage(failure,
                             jh_path_join(repository_root, ".build", &managed));
  const char *host_root = getenv("JH_MANAGED_BUILD_ROOT");
  bool within_host = false;
  if (status == HAL_OK && host_root != NULL && host_root[0] != '\0') {
    status = jh_python_resolve(host_root, NULL, &host, failure);
    within_host = status == HAL_OK &&
                  path_within(jh_string_span(&managed), jh_string_span(&host));
  }
  if (status == HAL_OK && !has_build_component(jh_string_span(&managed)) &&
      !within_host)
    status = jh_check_fail(
        failure,
        JH_PARTS(
            jh_span("output root must be a .build directory, one of its "
                    "descendants, or the runtime-managed build root; got "),
            jh_string_span(&managed)));
  if (status == HAL_OK &&
      !path_within(jh_string_span(out), jh_string_span(&managed)))
    status = jh_check_fail(failure,
                           JH_PARTS(jh_span("output directory must be below "),
                                    jh_string_span(&managed), jh_span(", got "),
                                    jh_string_span(out)));
  jb_string_destroy(&host);
  jb_string_destroy(&joined);
  jb_string_destroy(&managed);
  return status;
}

hal_status_t jh_board_write_outputs(const jh_board_outputs_t *outputs,
                                    const char *output_dir, size_t *changed,
                                    jh_failure_t *failure) {
  if (outputs == NULL || output_dir == NULL || changed == NULL)
    return jh_fail_arguments(failure);
  *changed = 0;
  hal_status_t status = jb_fs_mkdir(output_dir, true);
  if (status != HAL_OK)
    return jh_fail(failure, status, 3,
                   JH_PARTS(jh_span(output_dir),
                            jh_span(": cannot create the output directory: "),
                            jh_span(hal_status_to_string(status))));
  jb_string_t path = {0};
  status = jh_fail_storage(failure, text_init(&path));
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure, jh_path_join(output_dir, "jh_board_registry.h", &path));
  if (status == HAL_OK) {
    const hal_status_t removed = jb_fs_remove(jb_string_data(&path), false);
    if (removed != HAL_OK && removed != HAL_ENOENT)
      status =
          jh_fail(failure, removed, 3,
                  JH_PARTS(jh_string_span(&path), jh_span(": cannot remove: "),
                           jh_span(hal_status_to_string(removed))));
  }
  jh_generated_file_t files[JH_BOARD_OUTPUT_COUNT];
  for (size_t i = 0; i < JH_BOARD_OUTPUT_COUNT; ++i)
    files[i] = (jh_generated_file_t){jh_span(jh_board_output_names[i]),
                                     jh_string_span(&outputs->content[i])};
  bool current = true;
  if (status == HAL_OK)
    status = jh_publish_generated(output_dir, files, JH_BOARD_OUTPUT_COUNT,
                                  false, 0, 0, changed, &current, failure);
  jb_string_destroy(&path);
  return status;
}

