/* key in target["components"] or board["components"]. */
static bool uses_component(jb_json_tree_view_t target,
                           jb_json_tree_view_t board, const char *id) {
  return has(get(target, "components"), id, NULL) ||
         has(get(board, "components"), id, NULL);
}

/* board_compile_definitions: the definitions direct compiler consumers need
 * for the components of target and board, appended to out. */
static hal_status_t board_definitions(jb_json_tree_view_t target,
                                      jb_json_tree_view_t board,
                                      jb_vector_t *out) {
  static const char *const cyw43_pico[] = {
      "HAL_NETWORK_BACKEND_CYW43", "HAL_CYW43_BUS_PICO_PIO",
      "HAL_CYW43_STACK_LWIP", "HAL_CYW43_MAX_TRANSACTION_BYTES=2048u"};
  static const char *const cyw43_stm32[] = {
      "HAL_NETWORK_BACKEND_CYW43", "HAL_CYW43_BUS_STM32_GSPI",
      "HAL_CYW43_STACK_LWIP", "HAL_CYW43_MAX_TRANSACTION_BYTES=2048u"};
  hal_status_t status = HAL_OK;
  if (uses_component(target, board, "cyw43-pico-pio"))
    for (size_t i = 0; status == HAL_OK && i < COUNTOF(cyw43_pico); ++i)
      status = jh_list_push(out, jh_span(cyw43_pico[i]));
  if (status == HAL_OK && uses_component(target, board, "stm32g474-hse-24mhz"))
    status = jh_list_push(out, jh_span("HAL_STM32G474_CLOCK_HSE_160MHZ"));
  if (uses_component(target, board, "cyw43-stm32-gspi"))
    for (size_t i = 0; status == HAL_OK && i < COUNTOF(cyw43_stm32); ++i)
      status = jh_list_push(out, jh_span(cyw43_stm32[i]));
  return status;
}

static bool lists_equal(const jb_vector_t *a, const jb_vector_t *b) {
  if (jb_vector_size(a) != jb_vector_size(b))
    return false;
  for (size_t i = 0; i < jb_vector_size(a); ++i)
    if (!jh_span_equal(jh_string_span(jh_list_at(a, i)),
                       jh_string_span(jh_list_at(b, i))))
      return false;
  return true;
}

/* fallback_compile_definitions: the definitions every compatible target of
 * board gives it, or a failure when they differ. */
static hal_status_t fallback_definitions(const jh_board_registry_t *registry,
                                         jb_json_tree_view_t board,
                                         jb_vector_t *out,
                                         jh_failure_t *failure) {
  jb_vector_t variant = {0};
  hal_status_t status = jh_fail_storage(failure, jh_list_init(&variant));
  const jb_json_tree_view_t targets = get(board, "compatibleTargets");
  bool distinct = jh_json_count(targets) == 0;
  for (size_t i = 0;
       status == HAL_OK && !distinct && i < jh_json_count(targets); ++i) {
    const jh_board_descriptor_t *target =
        find_descriptor(&registry->targets, jh_json_item(targets, i));
    if (target == NULL) {
      distinct = true;
      break;
    }
    jh_list_destroy(&variant);
    status = jh_fail_storage(failure, jh_list_init(&variant));
    if (status == HAL_OK)
      status = jh_fail_storage(
          failure, board_definitions(target->root, board, &variant));
    if (status == HAL_OK && i == 0) {
      for (size_t d = 0; status == HAL_OK && d < jb_vector_size(&variant); ++d)
        status = jh_fail_storage(
            failure,
            jh_list_push(out, jh_string_span(jh_list_at(&variant, d))));
    } else if (status == HAL_OK) {
      distinct = !lists_equal(&variant, out);
    }
  }
  if (status == HAL_OK && distinct) {
    jb_string_t repr = {0};
    status = jh_fail_storage(failure, text_init(&repr));
    if (status == HAL_OK)
      status = jh_fail_storage(
          failure, jh_python_repr_append(&repr, text_of(get(board, "id"))));
    if (status == HAL_OK)
      status = jh_check_fail(
          failure,
          JH_PARTS(jh_span("board "), jh_string_span(&repr),
                   jh_span(" requires target-specific fallback definitions")));
    jb_string_destroy(&repr);
  }
  jh_list_destroy(&variant);
  return status;
}

