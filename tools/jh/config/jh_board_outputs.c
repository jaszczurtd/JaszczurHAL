/* selected_target_fact_lines. */
static hal_status_t target_facts(emit_t *e, jb_json_tree_view_t target,
                                 jh_failure_t *failure) {
  static const struct {
    const char *macro, *field;
  } names[] = {{"HAL_TARGET_VENDOR_NAME", "vendor"},
               {"HAL_TARGET_FAMILY_NAME", "family"},
               {"HAL_TARGET_SOC_NAME", "soc"},
               {"HAL_TARGET_ISA_NAME", "isa"},
               {"HAL_TARGET_BACKEND_NAME", "backendName"},
               {"HAL_TARGET_MCU_NAME", "mcuName"},
               {"HAL_TARGET_MCU_SUBTYPE_NAME", "mcuSubtype"},
               {"HAL_TARGET_CPU_ARCH_NAME", "cpuArchName"}};
  const jb_json_tree_view_t architecture = get(target, "architecture");
  put_define_string(e, "HAL_TARGET_DESCRIPTOR_ID", get(target, "id"));
  for (size_t i = 0; i < COUNTOF(names); ++i)
    put_define_string(e, names[i].macro, get(architecture, names[i].field));
  put(e, "#define HAL_TARGET_CPU_CORES ");
  put_value(e, get(architecture, "cores"));
  line(e, "u");
  put(e, "#define HAL_TARGET_HAS_FPU ");
  line(e, truthy(get(architecture, "hasFpu")) ? "1" : "0");
  const jb_json_tree_view_t memory = get(target, "memory");
  const jb_json_tree_view_t regions = get(memory, "regions");
  int64_t ram = 0;
  for (size_t i = 0; i < jh_json_count(regions); ++i) {
    const jb_json_tree_view_t region = jh_json_item(regions, i);
    if (text_is(get(region, "kind"), "ram"))
      ram += integer_of(get(region, "sizeBytes"));
  }
  put(e, "#define HAL_TARGET_RAM_TOTAL_BYTES UINT32_C(");
  put_int(e, ram);
  line(e, ")");
  put(e, "#define HAL_TARGET_RAM_USABLE_BYTES UINT32_C(");
  put_value(e, get(memory, "ramUsableBytes"));
  line(e, ")");
  jb_json_tree_view_t usb = {0};
  if (has(target, "usbDevice", &usb)) {
    line(e,
         "/** @brief Default USB device vendor ID of the selected target. */");
    put(e, "#define HAL_TARGET_USB_VID UINT16_C(");
    put_value(e, get(usb, "vid"));
    line(e, ")");
    line(e,
         "/** @brief Default USB device product ID of the selected target. */");
    put(e, "#define HAL_TARGET_USB_PID UINT16_C(");
    put_value(e, get(usb, "pid"));
    line(e, ")");
  }
  hal_status_t status = jh_fail_storage(failure, e->status);
  size_t words = 0;
  if (status == HAL_OK)
    status = jh_fail_storage(failure, target_words(target, &words));
  const jb_json_tree_view_t gpio = get(target, "gpio");
  static const struct {
    const char *trait, *macro;
  } masks[] = {{NULL, "HAL_TARGET_GPIO_VALID_MASK"},
               {"input-only", "HAL_TARGET_GPIO_INPUT_ONLY_MASK"},
               {"adc", "HAL_TARGET_GPIO_ADC_MASK"}};
  for (size_t i = 0; status == HAL_OK && i < COUNTOF(masks); ++i) {
    jb_json_tree_view_t set = get(gpio, "validPins");
    if (masks[i].trait != NULL &&
        (!has(get(gpio, "traits"), masks[i].trait, &set) || is_null(set)))
      continue;
    pin_mask_t mask;
    status = jh_fail_storage(failure, mask_init(&mask));
    if (status == HAL_OK)
      status = jh_fail_storage(failure, mask_add_set(&mask, set));
    if (status == HAL_OK)
      status = append_mask(e, masks[i].macro, &mask, words, failure);
    mask_destroy(&mask);
  }
  return status;
}

/* The board definitions of a header: #define NAME VALUE, or 1 for a bare
 * NAME. */
static void put_definitions(emit_t *e, const jb_vector_t *definitions) {
  if (jb_vector_size(definitions) != 0)
    line(e, "/* Board/provider definitions required by direct compiler "
            "consumers. */");
  for (size_t i = 0; i < jb_vector_size(definitions); ++i) {
    const jb_json_span_t definition =
        jh_string_span(jh_list_at(definitions, i));
    const char *equal = memchr(definition.data, '=', definition.length);
    put(e, "#define ");
    if (equal == NULL) {
      put_span(e, definition);
      line(e, " 1");
      continue;
    }
    const size_t name = (size_t)(equal - definition.data);
    put_span(e, (jb_json_span_t){definition.data, name});
    put(e, " ");
    put_span(e, (jb_json_span_t){equal + 1, definition.length - name - 1});
    end_line(e);
  }
}

/* The bus device of role among the devices of a board, the last one as a
 * dictionary keyed by role keeps it; a zero view when there is none. */
static bool role_device(jb_json_tree_view_t devices, const char *role,
                        jb_json_tree_view_t *out) {
  bool found = false;
  for (size_t i = 0; i < jh_json_count(devices); ++i) {
    const jb_json_tree_view_t device = jh_json_item(devices, i);
    if (text_is(get(device, "kind"), jh_board_bus_device_kind()) &&
        text_is(get(device, "role"), role)) {
      *out = device;
      found = true;
    }
  }
  return found;
}

/* The name after previous in code point order among count names reached by
 * name_at, or NULL. */
typedef const char *(*name_at_fn)(const void *items, size_t index);
static const char *signal_name(const void *items, size_t index) {
  return ((const jh_board_role_signal_t *)items)[index].name;
}
static const char *attribute_name(const void *items, size_t index) {
  return ((const jh_board_role_attribute_t *)items)[index].name;
}
static size_t next_index(const void *items, size_t count, name_at_fn name_at,
                         const char *previous) {
  size_t next = count;
  for (size_t i = 0; i < count; ++i) {
    const char *name = name_at(items, i);
    if ((previous == NULL || strcmp(name, previous) > 0) &&
        (next == count || strcmp(name, name_at(items, next)) < 0))
      next = i;
  }
  return next;
}

/* device_config_lines: the bus device facts of every known role. */
static void device_facts(emit_t *e, jb_json_tree_view_t board) {
  line(e, "#define HAL_BOARD_DEVICE_PIN_NONE 0xFFu");
  size_t role_count = 0;
  const jh_board_role_t *roles = jh_board_roles(&role_count);
  const jb_json_tree_view_t devices = get(board, "devices");
  for (size_t r = 0; r < role_count; ++r) {
    const jh_board_role_t *spec = &roles[r];
    jb_json_tree_view_t device = {0};
    const bool present = role_device(devices, spec->role, &device);
    put(e, "#define ");
    put(e, spec->macro_prefix);
    put(e, "_PRESENT ");
    line(e, present && truthy(device) ? "1" : "0");
    if (!present)
      continue;
    const jb_json_tree_view_t bus = get(device, "bus");
    put(e, "#define ");
    put(e, spec->macro_prefix);
    put(e, "_");
    put_macro_suffix(e, text_of(get(bus, "kind")));
    put(e, "_BUS ");
    put_value(e, get(bus, "index"));
    line(e, "u");
    const jb_json_tree_view_t signals = get(device, "signals");
    const char *previous = NULL;
    for (size_t k = 0; k < spec->signal_count; ++k) {
      const size_t at =
          next_index(spec->signals, spec->signal_count, signal_name, previous);
      previous = spec->signals[at].name;
      put(e, "#define ");
      put(e, spec->macro_prefix);
      put(e, "_PIN_");
      put_camel_suffix(e, previous);
      put(e, " ");
      jb_json_tree_view_t pin = {0};
      int64_t encoded = 0;
      if (!has(signals, previous, &pin) || is_null(pin)) {
        line(e, "HAL_BOARD_DEVICE_PIN_NONE");
        continue;
      }
      if (encode_pin(pin, &encoded))
        put_int(e, encoded);
      else
        put(e, "None");
      line(e, "u");
    }
    const jb_json_tree_view_t attributes = get(device, "attributes");
    previous = NULL;
    for (size_t k = 0; k < spec->attribute_count; ++k) {
      const size_t at = next_index(spec->attributes, spec->attribute_count,
                                   attribute_name, previous);
      const jh_board_role_attribute_t *attribute = &spec->attributes[at];
      previous = attribute->name;
      jb_json_tree_view_t value = {0};
      const bool given = has(attributes, attribute->name, &value);
      if (strcmp(attribute->type, "enum") == 0) {
        for (size_t v = 0; v < attribute->value_count; ++v) {
          put(e, "#define ");
          put(e, spec->macro_prefix);
          put(e, "_");
          put_camel_suffix(e, attribute->name);
          put(e, "_IS_");
          put_macro_suffix(e, jh_span(attribute->values[v]));
          line(e, given && text_is(value, attribute->values[v]) ? " 1" : " 0");
        }
        if (given && !is_null(value)) {
          put(e, "#define ");
          put(e, spec->macro_prefix);
          put(e, "_");
          put_camel_suffix(e, attribute->name);
          put(e, "_NAME \"");
          put_value(e, value);
          line(e, "\"");
        }
        continue;
      }
      if (!given)
        continue;
      put(e, "#define ");
      put(e, spec->macro_prefix);
      put(e, "_");
      put_camel_suffix(e, attribute->name);
      if (strcmp(attribute->type, "bool") == 0) {
        line(e, truthy(value) ? " 1" : " 0");
      } else if (strcmp(attribute->type, "uint32") == 0) {
        put(e, " UINT32_C(");
        put_value(e, value);
        line(e, ")");
      } else {
        put(e, " (");
        put_value(e, value);
        line(e, ")");
      }
    }
  }
}

/* can_config_lines: the channel count and the X-macro table
 * X(backend, instance, rx, tx, standby, standby_active_high, max_bitrate_hz).
 */
static void can_facts(emit_t *e, jb_json_tree_view_t board) {
  const jb_json_tree_view_t channels = get(get(board, "can"), "channels");
  const size_t count = jh_json_count(channels);
  /* Plain int: HAL_CAN_MAX_INSTANCES derives from it and stays an int. */
  put(e, "#define HAL_BOARD_CAN_CHANNEL_COUNT ");
  put_int(e, (int64_t)count);
  end_line(e);
  put(e, "#define HAL_BOARD_CAN_CHANNELS(X)");
  for (size_t i = 0; i < count; ++i) {
    const jb_json_tree_view_t channel = jh_json_item(channels, i);
    const jh_board_can_controller_t *controller =
        jh_board_can_controller(text_of(get(channel, "controller")));
    put(e, " X(");
    put(e, controller != NULL ? controller->backend : "None");
    put(e, ", ");
    put_value(e, get(channel, "instance"));
    put(e, "u, ");
    put_pin_text(e, get(channel, "rx"));
    put(e, ", ");
    put_pin_text(e, get(channel, "tx"));
    put(e, ", ");
    jb_json_tree_view_t standby = {0};
    if (has(channel, "standby", &standby) && !is_null(standby))
      put_pin_text(e, standby);
    else
      put(e, "HAL_BOARD_DEVICE_PIN_NONE");
    put(e, truthy(get(channel, "standbyActiveHigh")) ? ", 1" : ", 0");
    put(e, ", UINT32_C(");
    put_value(e, get(channel, "maxBitrateHz"));
    put(e, "))");
  }
  end_line(e);
}

/* The facts selected_board_fact_lines writes for one board. */
typedef struct {
  const jh_board_registry_t *registry;
  jb_json_tree_view_t board;
  const jb_vector_t *definitions;
  jb_json_span_t target_value;
  size_t gpio_words;
  bool define_selector, define_is_macros;
} board_facts_t;

static hal_status_t board_facts(emit_t *e, const board_facts_t *facts,
                                jh_failure_t *failure) {
  const jb_json_tree_view_t board = facts->board;
  const jb_json_tree_view_t hal = get(board, "hal");
  const jb_json_tree_view_t memory = get(board, "memory");
  const jb_json_tree_view_t flash_value =
      get(get(memory, "flash"), "expectedBytes");
  const int64_t flash = integer_of(flash_value);
  if (facts->define_selector) {
    put(e, "#define ");
    put_span(e, text_of(get(hal, "selector")));
    line(e, " 1");
  }
  put(e, "#define HAL_BOARD_PROFILE_ID ");
  put_board_enum(e, board);
  end_line(e);
  put_define_string(e, "HAL_BOARD_PROFILE_NAME", get(board, "id"));
  put(e, "#define HAL_BOARD_PROFILE_TARGET ");
  put_span(e, facts->target_value);
  end_line(e);
  put(e, "#define HAL_BOARD_PROVIDER_BOARD \"");
  jb_json_tree_view_t provider_board = {0};
  if (has(get(board, "build"), "board", &provider_board))
    put_value(e, provider_board);
  line(e, "\"");
  put(e, "#define HAL_BOARD_EXPECTED_FLASH_BYTES UINT32_C(");
  put_value(e, flash_value);
  line(e, ")");
  if (flash > 0 && flash % (1024 * 1024) == 0) {
    put(e, "#define HAL_BOARD_EXPECTED_FLASH_MIB ");
    put_int(e, flash / (1024 * 1024));
    end_line(e);
  }
  const jb_json_tree_view_t psram = get(memory, "psram");
  const bool has_psram = truthy(psram);
  put(e, "#define HAL_BOARD_HAS_PSRAM ");
  line(e, has_psram ? "1" : "0");
  put(e, "#define HAL_BOARD_PSRAM_BYTES UINT32_C(");
  if (has_psram)
    put_value(e, get(psram, "sizeBytes"));
  else
    put(e, "0");
  line(e, ")");
  if (has_psram) {
    put(e, "#define HAL_BOARD_PSRAM_INTERFACE_");
    const jb_json_span_t interface_name = text_of(get(psram, "interface"));
    for (size_t i = 0; e->status == HAL_OK && i < interface_name.length; ++i) {
      const char c = ascii_upper(interface_name.data[i]);
      e->status = jb_string_append(e->out, &c, 1);
    }
    line(e, " 1");
  }
  put_definitions(e, facts->definitions);
  hal_status_t status = jh_fail_storage(failure, e->status);
  jb_vector_t order = {0};
  if (status == HAL_OK && facts->define_is_macros)
    status = jh_fail_storage(failure,
                             ordered(&facts->registry->boards, true, &order));
  for (size_t i = 0; status == HAL_OK && facts->define_is_macros &&
                     i < jb_vector_size(&order);
       ++i) {
    const jh_board_descriptor_t *entry =
        descriptor_at(&facts->registry->boards, order_at(&order, i));
    put(e, "#define ");
    put_board_is(e, entry->root);
    line(e, jh_span_equal(jh_string_span(&entry->id), text_of(get(board, "id")))
                ? " 1"
                : " 0");
  }
  jb_vector_destroy(&order);
  const jb_json_tree_view_t legacy = get(hal, "legacySelectors");
  for (size_t i = 0; i < jh_json_count(legacy); ++i) {
    const jb_json_span_t selector = text_of(jh_json_item(legacy, i));
    put(e, "#ifndef ");
    put_span(e, selector);
    end_line(e);
    put(e, "#define ");
    put_span(e, selector);
    line(e, " 1");
    line(e, "#endif");
  }
  const jb_json_tree_view_t capabilities = facts->registry->capabilities;
  const jb_json_tree_view_t declared = get(board, "capabilities");
  if (status == HAL_OK)
    status = jh_fail_storage(failure, e->status);
  if (status == HAL_OK)
    status =
        jh_fail_storage(failure, ordered_members(capabilities, false, &order));
  uint64_t capability_mask = 0;
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t config =
        jh_json_item(capabilities, order_at(&order, i));
    const jb_json_span_t id = jh_json_key(config);
    jb_json_tree_view_t entry = {0};
    (void)jb_json_tree_find(declared, id, &entry);
    const bool present = truthy(get(entry, "present"));
    const jb_json_tree_view_t macro = get(entry, "macro");
    put(e, "#define HAL_BOARD_HAS_");
    put_macro_suffix(e, id);
    put(e, " ");
    if (truthy(macro))
      put_value(e, macro);
    else
      put(e, present ? "1" : "0");
    end_line(e);
    const int64_t bit = integer_of(get(config, "bit"));
    if (present && !text_is(get(config, "status"), "reserved") && bit >= 0 &&
        bit < 64)
      capability_mask |= UINT64_C(1) << (unsigned)bit;
  }
  jb_vector_destroy(&order);
  put(e, "#define HAL_BOARD_DECLARED_CAPABILITIES UINT32_C(0x");
  put_hex(e, capability_mask, 8);
  line(e, ")");
  if (status == HAL_OK)
    status = jh_fail_storage(failure, e->status);
  const jb_json_tree_view_t gpio = get(board, "gpio");
  pin_mask_t exposed, hard, soft;
  const bool masks_started = status == HAL_OK;
  if (masks_started) {
    status = jh_fail_storage(failure, mask_init(&exposed));
    hal_status_t more = mask_init(&hard);
    if (status == HAL_OK)
      status = jh_fail_storage(failure, more);
    more = mask_init(&soft);
    if (status == HAL_OK)
      status = jh_fail_storage(failure, more);
  }
  if (status == HAL_OK)
    status = jh_fail_storage(failure,
                             mask_add_set(&exposed, get(gpio, "exposedPins")));
  const jb_json_tree_view_t reservations = get(gpio, "reservations");
  for (size_t i = 0; status == HAL_OK && i < jh_json_count(reservations); ++i) {
    const jb_json_tree_view_t reservation = jh_json_item(reservations, i);
    status = jh_fail_storage(
        failure,
        mask_add_endpoints(
            text_is(get(reservation, "strength"), "hard") ? &hard : &soft,
            get(reservation, "pins")));
  }
  if (status == HAL_OK)
    status = append_mask(e, "HAL_BOARD_GPIO_EXPOSED_MASK", &exposed,
                         facts->gpio_words, failure);
  if (status == HAL_OK)
    status = append_mask(e, "HAL_BOARD_GPIO_HARD_RESERVED_MASK", &hard,
                         facts->gpio_words, failure);
  if (status == HAL_OK)
    status = append_mask(e, "HAL_BOARD_GPIO_SOFT_RESERVED_MASK", &soft,
                         facts->gpio_words, failure);
  if (masks_started) {
    mask_destroy(&soft);
    mask_destroy(&hard);
    mask_destroy(&exposed);
  }
  if (status != HAL_OK)
    return status;
  const jb_json_tree_view_t status_led =
      get(get(board, "devices"), "statusLed");
  if (truthy(status_led)) {
    const jb_json_tree_view_t kind = get(status_led, "kind");
    const jb_json_tree_view_t endpoint = get(status_led, "endpoint");
    put(e, "#define HAL_BOARD_STATUS_LED_KIND_");
    put_macro_suffix(e, text_of(kind));
    line(e, " 1");
    int64_t pin = 0;
    if (encode_pin(endpoint, &pin)) {
      put(e, "#define HAL_BOARD_STATUS_LED_PIN ");
      put_pin_text(e, endpoint);
      end_line(e);
    }
    if (text_is(kind, "gpio") || text_is(kind, "component-gpio"))
      line(e, "#define HAL_LED_BUILTIN HAL_BOARD_STATUS_LED_PIN");
    if (text_is(kind, "addressable")) {
      /* A board leaves the order to the project; an assembly chooses it. */
      const jb_json_tree_view_t order_value = get(status_led, "pixelOrder");
      jb_json_span_t pixel_order = jh_span("PROJECT_DEFINED");
      (void)jh_json_string(order_value, &pixel_order);
      line(e, "#define HAL_BOARD_STATUS_LED_PROTOCOL_WS2812 1");
      put(e, "#define HAL_BOARD_STATUS_LED_PIXEL_ORDER_");
      put_span(e, pixel_order);
      line(e, " 1");
    }
  }
  device_facts(e, board);
  can_facts(e, board);
  return jh_fail_storage(failure, e->status);
}

