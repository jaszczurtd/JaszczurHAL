/* ---- Descriptor values, read as the dictionaries of json.loads ---- */

/* key in object: *out receives the member value. */
static bool has(jb_json_tree_view_t object, const char *key,
                jb_json_tree_view_t *out) {
  jb_json_tree_view_t value = {0};
  const bool found = jb_json_tree_find(object, jh_span(key), &value) == HAL_OK;
  if (out != NULL)
    *out = value;
  return found;
}

/* object[key], or a zero view, which reads as None. */
static jb_json_tree_view_t get(jb_json_tree_view_t object, const char *key) {
  jb_json_tree_view_t value = {0};
  (void)has(object, key, &value);
  return value;
}

/* The bytes of a string; empty for any other value. */
static jb_json_span_t text_of(jb_json_tree_view_t value) {
  jb_json_span_t text = {"", 0};
  if (!jh_json_string(value, &text))
    text = (jb_json_span_t){"", 0};
  return text;
}

static int64_t integer_of(jb_json_tree_view_t value) {
  int64_t number = 0;
  (void)jh_json_int64(value, &number);
  return number;
}

static bool is_null(jb_json_tree_view_t value) {
  return jh_json_type(value) == JB_JSON_NULL;
}

static bool text_is(jb_json_tree_view_t value, const char *expected) {
  jb_json_span_t text = {NULL, 0};
  return jh_json_string(value, &text) && jh_span_equal(text, jh_span(expected));
}

/* bool(value) of Python. */
static bool truthy(jb_json_tree_view_t value) {
  switch (jh_json_type(value)) {
  case JB_JSON_BOOL: {
    bool flag = false;
    (void)jb_json_tree_get_bool(value, &flag);
    return flag;
  }
  case JB_JSON_NUMBER: {
    jb_json_span_t token = {NULL, 0};
    if (jb_json_tree_text(value, &token) != HAL_OK)
      return false;
    for (size_t i = 0; i < token.length; ++i) {
      const char c = token.data[i];
      if (c == 'e' || c == 'E')
        break;
      if (c >= '1' && c <= '9')
        return true;
    }
    return false;
  }
  case JB_JSON_STRING:
    return text_of(value).length != 0;
  case JB_JSON_ARRAY:
  case JB_JSON_OBJECT:
    return jh_json_count(value) != 0;
  default:
    return false;
  }
}

/* ---- Text builder ---- */

typedef struct {
  jb_string_t *out;
  hal_status_t status;
} emit_t;

static void put(emit_t *e, const char *text) {
  jh_put(e->out, &e->status, text);
}
static void put_span(emit_t *e, jb_json_span_t text) {
  jh_put_span(e->out, &e->status, text);
}
static void put_int(emit_t *e, int64_t value) {
  jh_put_int64(e->out, &e->status, value);
}
static void line(emit_t *e, const char *text) {
  put(e, text);
  put(e, "\n");
}
static void end_line(emit_t *e) { put(e, "\n"); }

static void put_hex(emit_t *e, uint64_t value, int digits) {
  char buffer[32];
  (void)snprintf(buffer, sizeof buffer, "%0*" PRIx64, digits, value);
  put(e, buffer);
}

/* f"{value}" of a JSON value: a string as is, an integer in decimal, True,
 * False and None; any other number keeps its token. */
static void put_value(emit_t *e, jb_json_tree_view_t value) {
  int64_t number = 0;
  switch (jh_json_type(value)) {
  case JB_JSON_STRING:
    put_span(e, text_of(value));
    return;
  case JB_JSON_BOOL:
    put(e, truthy(value) ? "True" : "False");
    return;
  case JB_JSON_NUMBER:
    if (jh_json_int64(value, &number)) {
      put_int(e, number);
    } else {
      jb_json_span_t token = {"", 0};
      (void)jb_json_tree_text(value, &token);
      put_span(e, token);
    }
    return;
  default:
    put(e, "None");
    return;
  }
}

static char ascii_upper(char c) {
  return c >= 'a' && c <= 'z' ? (char)(c - 'a' + 'A') : c;
}

/* identifier.upper().replace("-", "_"). */
static void put_macro_suffix(emit_t *e, jb_json_span_t identifier) {
  for (size_t i = 0; e->status == HAL_OK && i < identifier.length; ++i) {
    const char c =
        identifier.data[i] == '-' ? '_' : ascii_upper(identifier.data[i]);
    e->status = jb_string_append(e->out, &c, 1);
  }
}

/* re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper(). */
static void put_camel_suffix(emit_t *e, const char *name) {
  for (size_t i = 0; e->status == HAL_OK && name[i] != '\0'; ++i) {
    const char c = name[i];
    if (i > 0 && c >= 'A' && c <= 'Z') {
      const char p = name[i - 1];
      if ((p >= 'a' && p <= 'z') || (p >= '0' && p <= '9'))
        put(e, "_");
    }
    const char upper = ascii_upper(c);
    if (e->status == HAL_OK)
      e->status = jb_string_append(e->out, &upper, 1);
  }
}

/* identifier.replace("-", "_"). */
static void put_c_symbol(emit_t *e, jb_json_span_t identifier) {
  for (size_t i = 0; e->status == HAL_OK && i < identifier.length; ++i) {
    const char c = identifier.data[i] == '-' ? '_' : identifier.data[i];
    e->status = jb_string_append(e->out, &c, 1);
  }
}

/* selector.replace(prefix, replacement, 1). */
static void put_replaced(emit_t *e, jb_json_span_t text, const char *prefix,
                         const char *replacement) {
  const size_t length = strlen(prefix);
  for (size_t at = 0; at + length <= text.length; ++at) {
    if (memcmp(text.data + at, prefix, length) != 0)
      continue;
    put_span(e, (jb_json_span_t){text.data, at});
    put(e, replacement);
    put_span(e, (jb_json_span_t){text.data + at + length,
                                 text.length - at - length});
    return;
  }
  put_span(e, text);
}

static bool starts_with(jb_json_span_t text, const char *prefix) {
  const size_t length = strlen(prefix);
  return text.length >= length && memcmp(text.data, prefix, length) == 0;
}

/* ---- Pins ---- */

/* The HAL encoding of a validated pin ID: the integer, or for a string
 * P<port letter><0-15> (STM32) port * 16 + pin. */
static int64_t encode_id(jb_json_tree_view_t id) {
  int64_t pin = 0;
  jb_json_span_t name = {NULL, 0};
  if (jh_json_string(id, &name)) {
    for (size_t i = 2; i < name.length; ++i)
      pin = pin * 10 + (name.data[i] - '0');
    return name.length >= 3 ? (name.data[1] - 'A') * 16 + pin : 0;
  }
  (void)jh_json_int64(id, &pin);
  return pin;
}

/* encode_hal_pin: the HAL pin ID of an endpoint; false for None. */
static bool encode_pin(jb_json_tree_view_t endpoint, int64_t *out) {
  if (text_is(get(endpoint, "domain"), "soc-gpio")) {
    const jb_json_tree_view_t id = get(endpoint, "id");
    if (jh_json_type(id) != JB_JSON_STRING && !jh_json_int64(id, out))
      return false;
    *out = encode_id(id);
    return true;
  }
  jb_json_tree_view_t pin = {0};
  return has(endpoint, "halPin", &pin) && jh_json_int64(pin, out);
}

/* pin_text: the early hardware macro of an assembly, else <HAL pin>u. */
static void put_pin_text(emit_t *e, jb_json_tree_view_t endpoint) {
  const jb_json_tree_view_t macro = get(endpoint, "macro");
  if (truthy(macro)) {
    put_value(e, macro);
    return;
  }
  int64_t pin = 0;
  if (encode_pin(endpoint, &pin))
    put_int(e, pin);
  else
    put(e, "None");
  put(e, "u");
}

/* A set of encoded GPIO pins as 64-bit words. */
typedef struct {
  jb_vector_t words; /* uint64_t */
  int64_t highest;   /* -1 when empty */
} pin_mask_t;

static hal_status_t mask_init(pin_mask_t *mask) {
  static const jb_vector_t empty = {0};
  mask->words = empty;
  mask->highest = -1;
  return jb_vector_init(&mask->words, sizeof(uint64_t), jb_heap_allocator());
}

static void mask_destroy(pin_mask_t *mask) { jb_vector_destroy(&mask->words); }

static hal_status_t mask_add(pin_mask_t *mask, int64_t pin) {
  if (pin < 0 || pin > INT32_MAX)
    return HAL_EOVERFLOW;
  const size_t word = (size_t)pin / 64u;
  if (word >= jb_vector_size(&mask->words)) {
    const hal_status_t status = jb_vector_resize(&mask->words, word + 1u);
    if (status != HAL_OK)
      return status;
  }
  uint64_t *words = jb_vector_data(&mask->words);
  words[word] |= UINT64_C(1) << ((unsigned)pin % 64u);
  if (pin > mask->highest)
    mask->highest = pin;
  return HAL_OK;
}

/* expand_pin_set of a validated pin set: every pin of its ranges or values,
 * encoded into mask. */
static hal_status_t mask_add_set(pin_mask_t *mask, jb_json_tree_view_t set) {
  hal_status_t status = HAL_OK;
  jb_json_tree_view_t list = {0};
  if (has(set, "ranges", &list)) {
    for (size_t i = 0; status == HAL_OK && i < jh_json_count(list); ++i) {
      const jb_json_tree_view_t range = jh_json_item(list, i);
      const int64_t first = integer_of(get(range, "first"));
      const int64_t last = integer_of(get(range, "last"));
      for (int64_t pin = first; status == HAL_OK && pin <= last; ++pin)
        status = mask_add(mask, pin);
    }
    return status;
  }
  list = get(set, "values");
  for (size_t i = 0; status == HAL_OK && i < jh_json_count(list); ++i)
    status = mask_add(mask, encode_id(jh_json_item(list, i)));
  return status;
}

/* endpoint_gpio_pins: the SoC GPIO endpoints of a list, encoded into mask. */
static hal_status_t mask_add_endpoints(pin_mask_t *mask,
                                       jb_json_tree_view_t endpoints) {
  hal_status_t status = HAL_OK;
  for (size_t i = 0; status == HAL_OK && i < jh_json_count(endpoints); ++i) {
    const jb_json_tree_view_t endpoint = jh_json_item(endpoints, i);
    if (text_is(get(endpoint, "domain"), "soc-gpio"))
      status = mask_add(mask, encode_id(get(endpoint, "id")));
  }
  return status;
}

/* A pin outside the words of a mask: Python's IndexError, here a failure. */
static hal_status_t fail_pin_words(jh_failure_t *failure, const char *name) {
  return jh_fail(
      failure, HAL_EOVERFLOW, 2,
      JH_PARTS(jh_span(name), jh_span(": a pin lies outside the GPIO words of "
                                      "the target")));
}

/* append_gpio_mask: <name> for a single word, <name>_WORDS and each
 * <name>_<index>. */
static hal_status_t append_mask(emit_t *e, const char *name,
                                const pin_mask_t *mask, size_t words,
                                jh_failure_t *failure) {
  if (mask->highest >= 0 && (uint64_t)mask->highest / 64u >= words)
    return fail_pin_words(failure, name);
  const uint64_t *values = jb_vector_const_data(&mask->words);
  const size_t stored = jb_vector_size(&mask->words);
  if (words == 1) {
    put(e, "#define ");
    put(e, name);
    put(e, " UINT64_C(0x");
    put_hex(e, stored > 0 ? values[0] : 0, 16);
    line(e, ")");
  }
  put(e, "#define ");
  put(e, name);
  put(e, "_WORDS ");
  put_int(e, (int64_t)words);
  line(e, "u");
  for (size_t i = 0; i < words; ++i) {
    put(e, "#define ");
    put(e, name);
    put(e, "_");
    put_int(e, (int64_t)i);
    put(e, " UINT64_C(0x");
    put_hex(e, i < stored ? values[i] : 0, 16);
    line(e, ")");
  }
  return jh_fail_storage(failure, e->status);
}

/* gpio_word_count of one target: the words that hold its valid pins. */
static hal_status_t target_words(jb_json_tree_view_t target, size_t *words) {
  pin_mask_t mask;
  hal_status_t status = mask_init(&mask);
  if (status == HAL_OK)
    status = mask_add_set(&mask, get(get(target, "gpio"), "validPins"));
  if (status == HAL_OK)
    *words = (size_t)(mask.highest < 0 ? 0 : mask.highest) / 64u + 1u;
  mask_destroy(&mask);
  return status;
}

/* ---- Registry order ---- */

static const jh_board_descriptor_t *descriptor_at(const jb_vector_t *list,
                                                  size_t index) {
  return jb_vector_const_at(list, index);
}

/* Whether the item at a sorts after the item at b. */
typedef bool (*after_fn)(const void *items, size_t a, size_t b);

/* order becomes the indices 0..count-1 stable-sorted by after (insertion
 * sort, as sorted() keeps equal items in place). */
static hal_status_t sorted_indices(const void *items, size_t count,
                                   after_fn after, jb_vector_t *order) {
  hal_status_t status =
      jb_vector_init(order, sizeof(size_t), jb_heap_allocator());
  for (size_t i = 0; status == HAL_OK && i < count; ++i)
    status = jb_vector_append(order, &i, 1);
  size_t *indices = jb_vector_data(order);
  for (size_t i = 1; status == HAL_OK && i < count; ++i) {
    const size_t moving = indices[i];
    size_t at = i;
    for (; at > 0 && after(items, indices[at - 1], moving); --at)
      indices[at] = indices[at - 1];
    indices[at] = moving;
  }
  return status;
}

static int64_t profile_id(const jb_vector_t *list, size_t index) {
  return integer_of(
      get(get(descriptor_at(list, index)->root, "hal"), "profileId"));
}
static bool profile_after(const void *items, size_t a, size_t b) {
  return profile_id(items, a) > profile_id(items, b);
}
static bool id_after(const void *items, size_t a, size_t b) {
  return jh_span_compare(jh_string_span(&descriptor_at(items, a)->id),
                         jh_string_span(&descriptor_at(items, b)->id)) > 0;
}

/* Indices of the descriptors of list, sorted by the integer at
 * hal.profileId (by_profile) or by their id. */
static hal_status_t ordered(const jb_vector_t *list, bool by_profile,
                            jb_vector_t *order) {
  return sorted_indices(list, jb_vector_size(list),
                        by_profile ? profile_after : id_after, order);
}

static size_t order_at(const jb_vector_t *order, size_t index) {
  return *(const size_t *)jb_vector_const_at(order, index);
}

static bool bit_after(const void *items, size_t a, size_t b) {
  const jb_json_tree_view_t *object = items;
  return integer_of(get(jh_json_item(*object, a), "bit")) >
         integer_of(get(jh_json_item(*object, b), "bit"));
}
static bool key_after(const void *items, size_t a, size_t b) {
  const jb_json_tree_view_t *object = items;
  return jh_span_compare(jh_json_key(jh_json_item(*object, a)),
                         jh_json_key(jh_json_item(*object, b))) > 0;
}

/* Indices of the members of an object, sorted by key (by_bit false) or by
 * the integer at member.bit. */
static hal_status_t ordered_members(jb_json_tree_view_t object, bool by_bit,
                                    jb_vector_t *order) {
  return sorted_indices(&object, jh_json_count(object),
                        by_bit ? bit_after : key_after, order);
}

static const jh_board_descriptor_t *find_descriptor(const jb_vector_t *list,
                                                    jb_json_tree_view_t id) {
  return jh_board_registry_find(list, text_of(id));
}

