/* render_board_registry. */
static hal_status_t registry_header(const jh_board_registry_t *registry,
                                    emit_t *e, jh_failure_t *failure) {
  line(e, "#pragma once");
  line(e, static_banner);
  line(e, "#include <stdint.h>");
  line(e, "");
  line(e, "typedef enum {");
  jb_vector_t order = {0}, aliases = {0}, destinations = {0};
  hal_status_t status =
      jh_fail_storage(failure, ordered(&registry->boards, true, &order));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jh_list_init(&aliases));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jh_list_init(&destinations));
  jb_string_t text = {0};
  if (status == HAL_OK)
    status = jh_fail_storage(failure, text_init(&text));
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t board =
        descriptor_at(&registry->boards, order_at(&order, i))->root;
    put(e, "  ");
    put_board_enum(e, board);
    put(e, " = ");
    put_value(e, get(get(board, "hal"), "profileId"));
    line(e, ",");
  }
  /* enum_aliases: alias -> destination, a later board replacing an earlier
   * one, then written in alias order. */
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t board =
        descriptor_at(&registry->boards, order_at(&order, i))->root;
    const jb_json_tree_view_t legacy =
        get(get(board, "hal"), "legacySelectors");
    for (size_t s = 0; status == HAL_OK && s < jh_json_count(legacy); ++s) {
      const jb_json_span_t selector = text_of(jh_json_item(legacy, s));
      if (!starts_with(selector, "HAL_BOARD_PROFILE_"))
        continue;
      jb_string_clear(&text);
      emit_t alias = {&text, HAL_OK};
      put_replaced(&alias, selector, "HAL_BOARD_PROFILE_", "HAL_BOARD_");
      status = jh_fail_storage(failure, alias.status);
      size_t at = 0;
      while (status == HAL_OK && at < jb_vector_size(&aliases) &&
             !jh_span_equal(jh_string_span(jh_list_at(&aliases, at)),
                            jh_string_span(&text)))
        ++at;
      if (status != HAL_OK)
        break;
      jb_string_t destination = {0};
      status = jh_fail_storage(failure, text_init(&destination));
      emit_t name = {&destination, status};
      put_board_enum(&name, board);
      status = jh_fail_storage(failure, name.status);
      if (status == HAL_OK && at == jb_vector_size(&aliases)) {
        status = jh_fail_storage(failure,
                                 jh_list_push(&aliases, jh_string_span(&text)));
        if (status == HAL_OK)
          status = jh_fail_storage(
              failure,
              jh_list_push(&destinations, jh_string_span(&destination)));
      } else if (status == HAL_OK) {
        jb_string_t *slot = jb_vector_at(&destinations, at);
        status = jh_fail_storage(
            failure, jh_join(slot, JH_PARTS(jh_string_span(&destination))));
      }
      jb_string_destroy(&destination);
    }
  }
  const char *previous = NULL;
  for (size_t k = 0; status == HAL_OK && k < jb_vector_size(&aliases); ++k) {
    size_t next = jb_vector_size(&aliases);
    for (size_t i = 0; i < jb_vector_size(&aliases); ++i) {
      const char *name = jb_string_data(jh_list_at(&aliases, i));
      if ((previous == NULL || strcmp(name, previous) > 0) &&
          (next == jb_vector_size(&aliases) ||
           strcmp(name, jb_string_data(jh_list_at(&aliases, next))) < 0))
        next = i;
    }
    previous = jb_string_data(jh_list_at(&aliases, next));
    put(e, "  ");
    put(e, previous);
    put(e, " = ");
    put_span(e, jh_string_span(jh_list_at(&destinations, next)));
    line(e, ",");
  }
  line(e, "} hal_board_profile_t;");
  line(e, "");
  jb_vector_destroy(&order);
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure, ordered_members(registry->capabilities, true, &order));
  bool first = true;
  jb_string_clear(&text);
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t config =
        jh_json_item(registry->capabilities, order_at(&order, i));
    put(e, "#define ");
    put_value(e, get(config, "macro"));
    put(e, " (UINT32_C(1) << ");
    put_value(e, get(config, "bit"));
    line(e, ")");
    if (text_is(get(config, "status"), "reserved"))
      continue;
    emit_t all = {&text, HAL_OK};
    put(&all, first ? "" : " | ");
    put_value(&all, get(config, "macro"));
    first = false;
    status = jh_fail_storage(failure, all.status);
  }
  put(e, "#define HAL_BOARD_CAP_ALL (");
  put_span(e, jh_string_span(&text));
  line(e, ")");
  if (status == HAL_OK)
    status = jh_fail_storage(failure, e->status);
  jb_string_destroy(&text);
  jh_list_destroy(&destinations);
  jh_list_destroy(&aliases);
  jb_vector_destroy(&order);
  return status;
}

/* " && ".join(f"!defined({selector})") over the primary selectors. */
static void put_no_primary(emit_t *e, const jh_board_registry_t *registry,
                           const jb_vector_t *order) {
  for (size_t i = 0; i < jb_vector_size(order); ++i) {
    const jb_json_tree_view_t board =
        descriptor_at(&registry->boards, order_at(order, i))->root;
    put(e, i == 0 ? "!defined(" : " && !defined(");
    put_span(e, text_of(get(get(board, "hal"), "selector")));
    put(e, ")");
  }
}

static void put_if(emit_t *e, size_t index) {
  put(e, index == 0 ? "#if " : "#elif ");
}

/* render_board_fallback_config. */
static hal_status_t fallback_header(const jh_board_registry_t *registry,
                                    emit_t *e, jh_failure_t *failure) {
  jb_vector_t order = {0}, target_order = {0}, legacy = {0}, definitions = {0};
  hal_status_t status =
      jh_fail_storage(failure, ordered(&registry->boards, true, &order));
  if (status == HAL_OK)
    status = jh_fail_storage(failure,
                             ordered(&registry->targets, false, &target_order));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jh_list_init(&legacy));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jh_list_init(&definitions));
  const jb_vector_t *boards = &registry->boards;
  line(e, "#pragma once");
  line(e, static_banner);
  line(e, "");
  line(e, "#if defined(HAL_CYW43_PROFILE_PICO_W)");
  line(e, "#error \"HAL_CYW43_PROFILE_PICO_W is invalid; use "
          "HAL_CYW43_PROFILE_PICOW.\"");
  line(e, "#endif");
  line(e, "");
  line(e, "/* Resolve legacy selectors through descriptor target "
          "compatibility. */");
  /* legacy_boards: every legacy selector, sorted, with its boards. */
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t list =
        get(get(descriptor_at(boards, order_at(&order, i))->root, "hal"),
            "legacySelectors");
    for (size_t s = 0; status == HAL_OK && s < jh_json_count(list); ++s) {
      const jb_json_span_t selector = text_of(jh_json_item(list, s));
      if (!jh_list_contains(&legacy, selector))
        status = jh_fail_storage(failure, jh_list_push(&legacy, selector));
    }
  }
  jh_list_sort(&legacy);
  for (size_t l = 0; status == HAL_OK && l < jb_vector_size(&legacy); ++l) {
    const jb_json_span_t selector = jh_string_span(jh_list_at(&legacy, l));
    size_t matches = 0;
    jb_json_tree_view_t only = {0};
    for (size_t i = 0; i < jb_vector_size(&order); ++i) {
      const jb_json_tree_view_t board =
          descriptor_at(boards, order_at(&order, i))->root;
      const jb_json_tree_view_t list =
          get(get(board, "hal"), "legacySelectors");
      for (size_t s = 0; s < jh_json_count(list); ++s)
        if (jh_span_equal(text_of(jh_json_item(list, s)), selector)) {
          ++matches;
          only = board;
          break;
        }
    }
    put(e, "#if defined(");
    put_span(e, selector);
    line(e, ")");
    if (matches == 1) {
      const jb_json_span_t destination =
          text_of(get(get(only, "hal"), "selector"));
      put(e, "#ifndef ");
      put_span(e, destination);
      end_line(e);
      put(e, "#define ");
      put_span(e, destination);
      line(e, " 1");
      line(e, "#endif");
    } else {
      size_t branch = 0;
      for (size_t i = 0; i < jb_vector_size(&order); ++i) {
        const jb_json_tree_view_t board =
            descriptor_at(boards, order_at(&order, i))->root;
        const jb_json_tree_view_t list =
            get(get(board, "hal"), "legacySelectors");
        bool listed = false;
        for (size_t s = 0; s < jh_json_count(list); ++s)
          listed =
              listed || jh_span_equal(text_of(jh_json_item(list, s)), selector);
        if (!listed)
          continue;
        const jb_json_tree_view_t targets = get(board, "compatibleTargets");
        for (size_t t = 0; t < jh_json_count(targets); ++t) {
          const jh_board_descriptor_t *target =
              find_descriptor(&registry->targets, jh_json_item(targets, t));
          put_if(e, branch++);
          if (target != NULL)
            put_target_is(e, target->root);
          end_line(e);
          put(e, "#define ");
          put_span(e, text_of(get(get(board, "hal"), "selector")));
          line(e, " 1");
        }
      }
      line(e, "#else");
      put(e, "#error \"JaszczurHAL: ");
      put_span(e, selector);
      line(e, " has no board for the selected target.\"");
      line(e, "#endif");
    }
    line(e, "#endif");
    line(e, "");
  }
  /* auto_detect: (selector, board) in board order. */
  size_t detected = 0;
  for (size_t i = 0; i < jb_vector_size(&order); ++i)
    detected += jh_json_count(
        get(get(descriptor_at(boards, order_at(&order, i))->root, "hal"),
            "autoDetectSelectors"));
  if (detected != 0) {
    line(e, "/* Prefer an unambiguous provider board selector. */");
    put(e, "#if ");
    put_no_primary(e, registry, &order);
    put(e, " && (");
    size_t index = 0;
    for (size_t i = 0; i < jb_vector_size(&order); ++i) {
      const jb_json_tree_view_t list =
          get(get(descriptor_at(boards, order_at(&order, i))->root, "hal"),
              "autoDetectSelectors");
      for (size_t s = 0; s < jh_json_count(list); ++s) {
        put(e, index++ == 0 ? "defined(" : " + defined(");
        put_span(e, text_of(jh_json_item(list, s)));
        put(e, ")");
      }
    }
    line(e, ") > 1");
    line(e, "#error \"JaszczurHAL: multiple provider board selectors are "
            "active.\"");
    line(e, "#endif");
    put(e, "#if ");
    put_no_primary(e, registry, &order);
    end_line(e);
    index = 0;
    for (size_t i = 0; i < jb_vector_size(&order); ++i) {
      const jb_json_tree_view_t board =
          descriptor_at(boards, order_at(&order, i))->root;
      const jb_json_tree_view_t list =
          get(get(board, "hal"), "autoDetectSelectors");
      for (size_t s = 0; s < jh_json_count(list); ++s) {
        put_if(e, index++);
        put(e, "defined(");
        put_span(e, text_of(jh_json_item(list, s)));
        line(e, ")");
        put(e, "#define ");
        put_span(e, text_of(get(get(board, "hal"), "selector")));
        line(e, " 1");
      }
    }
    line(e, "#endif");
    line(e, "#endif");
    line(e, "");
  }
  line(e, "/* Apply only explicitly declared source-level fallbacks. */");
  put(e, "#if ");
  put_no_primary(e, registry, &order);
  end_line(e);
  size_t fallbacks = 0;
  for (size_t i = 0; i < jb_vector_size(&target_order); ++i) {
    const jb_json_tree_view_t target =
        descriptor_at(&registry->targets, order_at(&target_order, i))->root;
    jb_json_tree_view_t name = {0};
    if (!has(target, "sourceFallbackBoard", &name))
      continue;
    const jh_board_descriptor_t *board = find_descriptor(boards, name);
    put_if(e, fallbacks++);
    put_target_is(e, target);
    end_line(e);
    put(e, "#define ");
    if (board != NULL)
      put_span(e, text_of(get(get(board->root, "hal"), "selector")));
    line(e, " 1");
  }
  if (fallbacks != 0)
    line(e, "#else");
  line(e, "#error \"JaszczurHAL: unknown board. Configure through the board "
          "generator (JH_BOARD), define an explicit HAL_BOARD_PROFILE_*, or "
          "provide an unambiguous provider board selector.\"");
  if (fallbacks != 0)
    line(e, "#endif");
  line(e, "#endif");
  line(e, "");
  line(e, "/* Normalize every descriptor selector to a fixed 0/1 macro. */");
  for (size_t i = 0; i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t board =
        descriptor_at(boards, order_at(&order, i))->root;
    put(e, "#if defined(");
    put_span(e, text_of(get(get(board, "hal"), "selector")));
    line(e, ")");
    put(e, "#define ");
    put_board_is(e, board);
    line(e, " 1");
    line(e, "#else");
    put(e, "#define ");
    put_board_is(e, board);
    line(e, " 0");
    line(e, "#endif");
    line(e, "");
  }
  put(e, "#if (");
  for (size_t i = 0; i < jb_vector_size(&order); ++i) {
    put(e, i == 0 ? "" : " + ");
    put_board_is(e, descriptor_at(boards, order_at(&order, i))->root);
  }
  line(e, ") != 1");
  line(e, "#error \"JaszczurHAL: exactly one HAL_BOARD_PROFILE_* must be "
          "selected.\"");
  line(e, "#endif");
  line(e, "");
  line(e, "/* Validate descriptor target compatibility. */");
  for (size_t i = 0; i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t board =
        descriptor_at(boards, order_at(&order, i))->root;
    put(e, "#if ");
    put_board_is(e, board);
    put(e, " && !(");
    const jb_json_tree_view_t targets = get(board, "compatibleTargets");
    for (size_t t = 0; t < jh_json_count(targets); ++t) {
      const jh_board_descriptor_t *target =
          find_descriptor(&registry->targets, jh_json_item(targets, t));
      put(e, t == 0 ? "" : " || ");
      if (target != NULL)
        put_target_is(e, target->root);
    }
    line(e, ")");
    put(e, "#error \"JaszczurHAL: board ");
    put_value(e, get(board, "id"));
    line(e, " is incompatible with the selected target.\"");
    line(e, "#endif");
  }
  line(e, "");
  line(e, "/* Materialize the selected target facts. */");
  if (status == HAL_OK)
    status = jh_fail_storage(failure, e->status);
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&target_order);
       ++i) {
    const jb_json_tree_view_t target =
        descriptor_at(&registry->targets, order_at(&target_order, i))->root;
    put_if(e, i);
    put_target_is(e, target);
    end_line(e);
    status = target_facts(e, target, failure);
  }
  line(e, "#endif");
  line(e, "");
  line(e, "/* Materialize the selected board facts. */");
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(&order); ++i) {
    const jb_json_tree_view_t board =
        descriptor_at(boards, order_at(&order, i))->root;
    put_if(e, i);
    put_board_is(e, board);
    end_line(e);
    jh_list_destroy(&definitions);
    status = jh_fail_storage(failure, jh_list_init(&definitions));
    if (status == HAL_OK)
      status = fallback_definitions(registry, board, &definitions, failure);
    size_t words = 0;
    const jb_json_tree_view_t targets = get(board, "compatibleTargets");
    for (size_t t = 0; status == HAL_OK && t < jh_json_count(targets); ++t) {
      const jh_board_descriptor_t *target =
          find_descriptor(&registry->targets, jh_json_item(targets, t));
      size_t target_count = 0;
      if (target != NULL)
        status =
            jh_fail_storage(failure, target_words(target->root, &target_count));
      if (target_count > words)
        words = target_count;
    }
    const board_facts_t facts = {
        registry, board, &definitions, jh_span("HAL_TARGET_NAME"),
        words,    false, false};
    if (status == HAL_OK)
      status = board_facts(e, &facts, failure);
  }
  line(e, "#endif");
  if (status == HAL_OK)
    status = jh_fail_storage(failure, e->status);
  jh_list_destroy(&definitions);
  jh_list_destroy(&legacy);
  jb_vector_destroy(&target_order);
  jb_vector_destroy(&order);
  return status;
}

/* render_board_components_cmake. */
static hal_status_t components_cmake(const jh_board_registry_t *registry,
                                     emit_t *e, jh_failure_t *failure) {
  line(e, "# Generated by jh generate boards; do not edit.");
  line(e, "set(JH_BOARD_COMPONENT_IDS");
  const size_t count = jb_vector_size(&registry->components);
  for (size_t i = 0; i < count; ++i) {
    const jh_board_component_t *component =
        jb_vector_const_at(&registry->components, i);
    put(e, "    ");
    put_span(e, jh_string_span(&component->id));
    end_line(e);
  }
  line(e, ")");
  jb_vector_t providers = {0};
  hal_status_t status = jh_fail_storage(failure, jh_list_init(&providers));
  for (size_t i = 0; status == HAL_OK && i < count; ++i) {
    const jh_board_component_t *component =
        jb_vector_const_at(&registry->components, i);
    jh_list_destroy(&providers);
    status = jh_fail_storage(failure, jh_list_init(&providers));
    for (size_t p = 0;
         status == HAL_OK && p < jb_vector_size(&component->providers); ++p)
      status = jh_fail_storage(
          failure,
          jh_list_push(&providers,
                       jh_string_span(jh_list_at(&component->providers, p))));
    jh_list_sort(&providers);
    end_line(e);
    put(e, "set(JH_BOARD_COMPONENT_");
    put_c_symbol(e, jh_string_span(&component->id));
    put(e, "_PROVIDERS \"");
    for (size_t p = 0; p < jb_vector_size(&providers); ++p) {
      put(e, p == 0 ? "" : ";");
      put_span(e, jh_string_span(jh_list_at(&providers, p)));
    }
    line(e, "\")");
    put(e, "set(JH_BOARD_COMPONENT_");
    put_c_symbol(e, jh_string_span(&component->id));
    put(e, "_SLOT \"");
    put_span(e, jh_string_span(&component->slot));
    line(e, "\")");
  }
  jh_list_destroy(&providers);
  return status == HAL_OK ? jh_fail_storage(failure, e->status) : status;
}

hal_status_t jh_board_static_text(const jh_board_registry_t *registry,
                                  int artifact, jb_string_t *out,
                                  jh_failure_t *failure) {
  if (registry == NULL || out == NULL || artifact < 0 ||
      artifact >= JH_BOARD_STATIC_COUNT)
    return jh_fail_arguments(failure);
  jb_string_clear(out);
  emit_t e = {out, HAL_OK};
  switch (artifact) {
  case JH_BOARD_STATIC_REGISTRY:
    return registry_header(registry, &e, failure);
  case JH_BOARD_STATIC_FALLBACK:
    return fallback_header(registry, &e, failure);
  default:
    return components_cmake(registry, &e, failure);
  }
}

hal_status_t jh_board_static_publish(const jh_board_registry_t *registry,
                                     const char *root, const char *output_root,
                                     bool check, size_t *changed, bool *current,
                                     jh_failure_t *failure) {
  if (registry == NULL || root == NULL || output_root == NULL ||
      changed == NULL || current == NULL)
    return jh_fail_arguments(failure);
  jb_string_t paths[JH_BOARD_STATIC_COUNT] = {{0}};
  jb_string_t contents[JH_BOARD_STATIC_COUNT] = {{0}};
  hal_status_t status = HAL_OK;
  for (size_t i = 0; status == HAL_OK && i < JH_BOARD_STATIC_COUNT; ++i) {
    status = jh_fail_storage(failure, text_init(&paths[i]));
    if (status == HAL_OK)
      status = jh_fail_storage(failure, text_init(&contents[i]));
  }
  if (status == HAL_OK)
    status = jh_generated_artifact_paths(root, jh_board_static_keys,
                                         JH_BOARD_STATIC_COUNT, paths, failure);
  for (int i = 0; status == HAL_OK && i < JH_BOARD_STATIC_COUNT; ++i)
    status = jh_board_static_text(registry, i, &contents[i], failure);
  if (status == HAL_OK) {
    jh_generated_file_t files[JH_BOARD_STATIC_COUNT];
    for (size_t i = 0; i < JH_BOARD_STATIC_COUNT; ++i)
      files[i] = (jh_generated_file_t){jh_string_span(&paths[i]),
                                       jh_string_span(&contents[i])};
    status = jh_publish_generated(output_root, files, JH_BOARD_STATIC_COUNT,
                                  check, 0, 120, changed, current, failure);
  }
  for (size_t i = 0; i < JH_BOARD_STATIC_COUNT; ++i) {
    jb_string_destroy(&contents[i]);
    jb_string_destroy(&paths[i]);
  }
  return status;
}

/* ---- Build configuration ---- */

/* The repr of text between prefix and suffix as a configuration failure. */
static hal_status_t fail_repr(jh_failure_t *failure, const char *prefix,
                              jb_json_span_t text, const char *suffix) {
  jb_string_t repr = {0};
  hal_status_t status = jh_fail_storage(failure, text_init(&repr));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jh_python_repr_append(&repr, text));
  if (status == HAL_OK)
    status =
        jh_check_fail(failure, JH_PARTS(jh_span(prefix), jh_string_span(&repr),
                                        jh_span(suffix)));
  jb_string_destroy(&repr);
  return status;
}

static bool feature_char(char c) {
  return (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_';
}

/* FEATURE_PATTERN.fullmatch: (-D)?HAL_(ENABLE|DISABLE)_[A-Z0-9_]+(=.*)?,
 * where . matches no line feed; value receives the text after =. */
static bool feature_definition(jb_json_span_t text, bool *has_value,
                               jb_json_span_t *value) {
  size_t at = starts_with(text, "-D") ? 2u : 0u;
  const jb_json_span_t rest = {text.data + at, text.length - at};
  if (starts_with(rest, "HAL_ENABLE_"))
    at += strlen("HAL_ENABLE_");
  else if (starts_with(rest, "HAL_DISABLE_"))
    at += strlen("HAL_DISABLE_");
  else
    return false;
  const size_t name = at;
  while (at < text.length && feature_char(text.data[at]))
    ++at;
  if (at == name)
    return false;
  *has_value = at < text.length;
  if (!*has_value)
    return true;
  if (text.data[at] != '=' ||
      memchr(text.data + at + 1, '\n', text.length - at - 1) != NULL)
    return false;
  *value = (jb_json_span_t){text.data + at + 1, text.length - at - 1};
  return true;
}

static bool contains(jb_json_span_t text, const char *needle) {
  const size_t length = strlen(needle);
  for (size_t at = 0; at + length <= text.length; ++at)
    if (memcmp(text.data + at, needle, length) == 0)
      return true;
  return false;
}

hal_status_t jh_board_validate_definitions(const jb_vector_t *definitions,
                                           jh_failure_t *failure) {
  if (definitions == NULL)
    return jh_fail_arguments(failure);
  for (size_t i = 0; i < jb_vector_size(definitions); ++i) {
    const jb_json_span_t definition =
        jh_string_span(jh_list_at(definitions, i));
    jb_json_span_t value = definition;
    (void)jh_python_strip(definition, &value);
    if (contains(value, "$<"))
      return fail_repr(failure, "[JH-CFG-VALUE] compile definition ",
                       definition, ": generator expressions are not supported");
    jb_json_span_t normalized = value;
    if (starts_with(normalized, "-D"))
      normalized = (jb_json_span_t){value.data + 2, value.length - 2};
    if (!starts_with(normalized, "HAL_ENABLE_") &&
        !starts_with(normalized, "HAL_DISABLE_")) {
      if (contains(normalized, "HAL_ENABLE_") ||
          contains(normalized, "HAL_DISABLE_"))
        return fail_repr(failure, "[JH-CFG-VALUE] compile definition ",
                         definition,
                         ": HAL feature symbols must be standalone bare macros "
                         "or have an explicit value of 1");
      continue;
    }
    bool has_value = false;
    jb_json_span_t given = {NULL, 0};
    if (!feature_definition(value, &has_value, &given) ||
        (has_value && !jh_span_equal(given, jh_span("1"))))
      return fail_repr(failure, "[JH-CFG-VALUE] compile definition ",
                       definition,
                       ": HAL feature symbols accept only a bare macro or an "
                       "explicit value of 1");
  }
  return HAL_OK;
}

hal_status_t jh_board_check_selectors(jb_json_tree_view_t board,
                                      const jb_vector_t *definitions,
                                      jh_failure_t *failure) {
  if (definitions == NULL)
    return jh_fail_arguments(failure);
  const jb_json_tree_view_t hal = get(board, "hal");
  const jb_json_tree_view_t legacy = get(hal, "legacySelectors");
  for (size_t i = 0; i < jb_vector_size(definitions); ++i) {
    const jb_json_span_t definition =
        jh_string_span(jh_list_at(definitions, i));
    const char *equal = memchr(definition.data, '=', definition.length);
    const jb_json_span_t selector = {
        definition.data,
        equal == NULL ? definition.length : (size_t)(equal - definition.data)};
    if (!starts_with(selector, "HAL_BOARD_PROFILE_") &&
        !starts_with(selector, "HAL_CYW43_PROFILE_"))
      continue;
    bool accepted = jh_span_equal(selector, text_of(get(hal, "selector")));
    for (size_t s = 0; !accepted && s < jh_json_count(legacy); ++s)
      accepted = jh_span_equal(selector, text_of(jh_json_item(legacy, s)));
    if (accepted)
      continue;
    jb_string_t message = {0};
    hal_status_t status = jh_fail_storage(failure, text_init(&message));
    jh_put(&message, &status, "compile definition ");
    if (status == HAL_OK)
      status = jh_python_repr_append(&message, selector);
    jh_put(&message, &status, " conflicts with resolved board ");
    if (status == HAL_OK)
      status = jh_python_repr_append(&message, text_of(get(board, "id")));
    status = status == HAL_OK
                 ? jh_check_fail(failure, JH_PARTS(jh_string_span(&message)))
                 : jh_fail_storage(failure, status);
    jb_string_destroy(&message);
    return status;
  }
  return HAL_OK;
}

hal_status_t jh_board_outputs_init(jh_board_outputs_t *outputs) {
  if (outputs == NULL)
    return HAL_EINVAL;
  hal_status_t status = HAL_OK;
  for (size_t i = 0; status == HAL_OK && i < JH_BOARD_OUTPUT_COUNT; ++i)
    status = text_init(&outputs->content[i]);
  if (status != HAL_OK)
    jh_board_outputs_destroy(outputs);
  return status;
}

void jh_board_outputs_destroy(jh_board_outputs_t *outputs) {
  if (outputs == NULL)
    return;
  for (size_t i = 0; i < JH_BOARD_OUTPUT_COUNT; ++i)
    jb_string_destroy(&outputs->content[i]);
}

/* Path.as_posix(): / separators on Windows; elsewhere a backslash is a file
 * name character. */
static void put_posix(emit_t *e, jb_json_span_t path) {
#ifdef _WIN32
  for (size_t i = 0; e->status == HAL_OK && i < path.length; ++i) {
    const char c = path.data[i] == '\\' ? '/' : path.data[i];
    e->status = jb_string_append(e->out, &c, 1);
  }
#else
  put_span(e, path);
#endif
}

/* The input roots of a generation: the boards directory and the config
 * directory of the checkout, both resolved. */
static hal_status_t input_roots(const jh_board_build_t *build,
                                jb_string_t roots[2], jh_failure_t *failure) {
  jb_string_t config = {0};
  hal_status_t status = jh_fail_storage(failure, text_init(&config));
  if (status == HAL_OK)
    status = jh_path_join(build->checkout_root, "config", &config);
  if (status == HAL_OK)
    status = jh_resolved_path(jb_string_data(&build->registry->boards_root),
                              &roots[0]);
  if (status == HAL_OK)
    status = jh_resolved_path(jb_string_data(&config), &roots[1]);
  jb_string_destroy(&config);
  return jh_fail_storage(failure, status);
}

/* Each regular *.json file under a root, resolved, as one line. */
typedef struct {
  emit_t *e;
  jb_string_t resolved;
} inputs_t;

static hal_status_t add_input(void *user, const char *path,
                              jb_json_span_t relative, const char *name) {
  (void)relative;
  inputs_t *inputs = user;
  const size_t length = strlen(name);
  if (length < 5 || strcmp(name + length - 5, ".json") != 0)
    return HAL_OK;
  hal_status_t status = jh_resolved_path(path, &inputs->resolved);
  if (status != HAL_OK)
    return status;
  put_posix(inputs->e, jh_string_span(&inputs->resolved));
  end_line(inputs->e);
  return inputs->e->status;
}

/* generation.d: the JSON files under the input roots, then the extra
 * inputs; and the globs of new input files for jh_board_config.cmake. */
static hal_status_t dependencies(const jh_board_build_t *build,
                                 const jb_string_t roots[2], emit_t *e,
                                 jh_failure_t *failure) {
  const size_t start = jb_string_size(e->out);
  inputs_t inputs = {e, {0}};
  hal_status_t status = jh_fail_storage(failure, text_init(&inputs.resolved));
  for (size_t i = 0; status == HAL_OK && i < 2; ++i) {
    status = jh_walk_files(jb_string_data(&roots[i]), jh_span(""), add_input,
                           &inputs, failure);
    if (status != HAL_OK && jb_string_size(&failure->message) == 0)
      status = jh_fail_storage(failure, status);
  }
  const jb_vector_t *extra =
      build->overrides != NULL ? build->overrides->generation_extra : NULL;
  for (size_t i = 0;
       status == HAL_OK && extra != NULL && i < jb_vector_size(extra); ++i) {
    put_posix(e, jh_string_span(jh_list_at(extra, i)));
    end_line(e);
    status = jh_fail_storage(failure, e->status);
  }
  /* "\n".join(paths) + "\n" of no paths. */
  if (status == HAL_OK && jb_string_size(e->out) == start) {
    end_line(e);
    status = jh_fail_storage(failure, e->status);
  }
  jb_string_destroy(&inputs.resolved);
  return status;
}

static void put_list(emit_t *e, const jb_vector_t *list,
                     const char *separator) {
  for (size_t i = 0; i < jb_vector_size(list); ++i) {
    put(e, i == 0 ? "" : separator);
    put_span(e, jh_string_span(jh_list_at(list, i)));
  }
}

static void put_cmake_set(emit_t *e, const char *name) {
  put(e, "set(");
  put(e, name);
  put(e, " \"");
}

/* Members of the resolved record, compact, from the jhbase writer. */
static hal_status_t write_strings(jb_json_writer_t *writer, const char *key,
                                  const jb_vector_t *list) {
  hal_status_t status = jb_json_writer_key(writer, jh_span(key));
  if (status == HAL_OK)
    status = jb_json_writer_array_begin(writer);
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(list); ++i)
    status = jb_json_writer_string(writer, jh_string_span(jh_list_at(list, i)));
  return status == HAL_OK ? jb_json_writer_array_end(writer) : status;
}

static hal_status_t write_text(jb_json_writer_t *writer, const char *key,
                               jb_json_span_t text) {
  const hal_status_t status = jb_json_writer_key(writer, jh_span(key));
  return status == HAL_OK ? jb_json_writer_string(writer, text) : status;
}

/* A member of a descriptor, or null when absent (dict.get). */
static hal_status_t write_member(jb_json_writer_t *writer, const char *key,
                                 jb_json_tree_view_t object,
                                 const char *member) {
  hal_status_t status = jb_json_writer_key(writer, jh_span(key));
  jb_json_tree_view_t value = {0};
  if (status == HAL_OK)
    status = has(object, member, &value) ? jh_json_write_tree(writer, value)
                                         : jb_json_writer_null(writer);
  return status;
}

typedef struct {
  const jh_board_build_t *build;
  const jh_feature_resolution_t *resolution;
  const jb_vector_t *components, *cmake_definitions;
  jb_json_span_t feature_hash, contract_symbol;
} resolved_record_t;

/* The compact jh_board_resolved.json record before formatting. */
static hal_status_t write_record(jb_json_writer_t *writer,
                                 const resolved_record_t *record) {
  const jb_json_tree_view_t target = record->build->target;
  const jb_json_tree_view_t board = record->build->board;
  const jb_json_tree_view_t board_build = get(board, "build");
  const jb_json_tree_view_t target_build = get(target, "build");
  const jb_json_tree_view_t hal = get(board, "hal");
  const jh_feature_resolution_t *resolution = record->resolution;
  hal_status_t status = jb_json_writer_object_begin(writer);
  if (status == HAL_OK)
    status = jb_json_writer_key(writer, jh_span("schemaVersion"));
  if (status == HAL_OK)
    status = jb_json_writer_u64(writer, 1);
  if (status == HAL_OK)
    status = write_member(writer, "target", target, "id");
  if (status == HAL_OK)
    status = write_member(writer, "board", board, "id");
  if (status == HAL_OK)
    status = write_member(writer, "provider", board_build, "provider");
  if (status == HAL_OK)
    status = write_member(writer, "providerBoard", board_build, "board");
  if (status == HAL_OK)
    status = write_member(writer, "platform", target_build, "platform");
  if (status == HAL_OK)
    status = write_member(writer, "idfTarget", target_build, "idfTarget");
  if (status == HAL_OK)
    status = write_member(writer, "recipe", target_build, "recipe");
  if (status == HAL_OK)
    status = write_member(writer, "profileId", hal, "profileId");
  if (status == HAL_OK)
    status = write_member(writer, "selector", hal, "selector");
  if (status == HAL_OK)
    status = write_member(writer, "runtimeName", board, "id");
  if (status == HAL_OK)
    status = write_member(writer, "flashBytes",
                          get(get(board, "memory"), "flash"), "expectedBytes");
  if (status == HAL_OK)
    status = write_member(writer, "psram", get(board, "memory"), "psram");
  if (status == HAL_OK)
    status = write_strings(writer, "components", record->components);
  if (status == HAL_OK)
    status = write_strings(writer, "boardCompileDefinitions",
                           record->cmake_definitions);
  if (status == HAL_OK)
    status = write_strings(writer, "requestedFeatures", &resolution->requested);
  if (status == HAL_OK)
    status = write_strings(writer, "resolvedFeatures", &resolution->resolved);
  if (status == HAL_OK)
    status = jb_json_writer_key(writer, jh_span("featureProvenance"));
  if (status == HAL_OK)
    status = jb_json_writer_object_begin(writer);
  for (size_t i = 0;
       status == HAL_OK && i < jb_vector_size(&resolution->provenance); ++i) {
    const jh_feature_provenance_t *entry =
        jb_vector_const_at(&resolution->provenance, i);
    const jb_string_t symbol = entry->symbol;
    status = write_strings(writer, jb_string_data(&symbol), &entry->sources);
  }
  if (status == HAL_OK)
    status = jb_json_writer_object_end(writer);
  if (status == HAL_OK)
    status = write_text(writer, "resolvedFeaturesDigest",
                        jh_span(resolution->digest));
  if (status == HAL_OK)
    status = write_strings(writer, "features", &resolution->resolved);
  if (status == HAL_OK)
    status = write_text(writer, "featureHash", record->feature_hash);
  if (status == HAL_OK)
    status = write_text(writer, "contractSymbol", record->contract_symbol);
  if (status == HAL_OK)
    status = write_member(writer, "capabilities", board, "capabilities");
  if (status == HAL_OK)
    status = write_member(writer, "gpio", board, "gpio");
  if (status == HAL_OK) {
    status = jb_json_writer_key(writer, jh_span("clockSources"));
    jb_json_tree_view_t sources = {0};
    if (status == HAL_OK)
      status = has(board, "clockSources", &sources)
                   ? jh_json_write_tree(writer, sources)
                   : (jb_json_writer_object_begin(writer) == HAL_OK
                          ? jb_json_writer_object_end(writer)
                          : HAL_ENOMEM);
  }
  if (status == HAL_OK)
    status = write_member(writer, "targetGpio", target, "gpio");
  if (status == HAL_OK)
    status = write_member(writer, "devices", board, "devices");
  if (status == HAL_OK)
    status = write_member(writer, "peripherals", board, "peripherals");
  return status == HAL_OK ? jb_json_writer_object_end(writer) : status;
}

/* json.dumps(resolved, indent=2, sort_keys=True) + "\n". */
static hal_status_t resolved_json(const resolved_record_t *record,
                                  jb_string_t *out, jh_failure_t *failure) {
  jb_string_t compact = {0};
  jb_vector_t scratch = {0};
  jb_json_tree_t *tree = NULL;
  hal_status_t status = jh_fail_storage(failure, text_init(&compact));
  if (status == HAL_OK)
    status = jh_fail_storage(failure,
                             jb_vector_init(&scratch, 1, jb_heap_allocator()));
  const jb_json_writer_limits_t limits = {SIZE_MAX / 2, 64, 65536, 1048576,
                                          SIZE_MAX / 2};
  size_t bytes = 0;
  if (status == HAL_OK)
    status = jh_fail_storage(failure,
                             jb_json_writer_workspace_size(&limits, &bytes));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jb_vector_resize(&scratch, bytes));
  jb_json_writer_t writer = {NULL, HAL_NONE};
  const jb_json_workspace_t work = {jb_vector_data(&scratch),
                                    jb_vector_size(&scratch)};
  if (status == HAL_OK)
    status =
        jh_fail_storage(failure, jb_json_writer_init(&writer, &limits, work,
                                                     jh_string_sink, &compact));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, write_record(&writer, record));
  size_t written = 0;
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jb_json_writer_finish(&writer, &written));
  const size_t length = jb_string_size(&compact);
  const jb_json_limits_t parse_limits = {
      length,     length + 1,        64, length, length + 1,
      length + 1, length * 64 + 4096};
  const jb_json_tree_limits_t tree_limits = {length + 1, 64, length,
                                             length * 64 + 4096};
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure, jb_json_tree_parse(jh_string_span(&compact), &parse_limits,
                                    &tree_limits, 0, &tree, NULL));
  jb_json_tree_view_t root = {0};
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jb_json_tree_root(tree, &root));
  const jb_json_tree_format_t format = {SIZE_MAX / 2, 2, true, true};
  jb_string_clear(out);
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure,
        jb_json_tree_format(root, &format, jh_string_sink, out, &written));
  if (status == HAL_OK)
    status = jh_fail_storage(failure, jh_append(out, "\n"));
  jb_json_tree_destroy(tree);
  jb_vector_destroy(&scratch);
  jb_string_destroy(&compact);
  return status;
}

static void put_sha256_hex(emit_t *e, jb_json_span_t text, size_t digits) {
  jh_sha256_context_t context;
  uint8_t digest[JH_SHA256_DIGEST_BYTES];
  jh_sha256_init(&context);
  jh_sha256_update(&context, (const uint8_t *)text.data, text.length);
  jh_sha256_final(&context, digest);
  for (size_t i = 0; i < JH_SHA256_DIGEST_BYTES && i * 2 < digits; ++i)
    put_hex(e, digest[i], 2);
}

/* sorted(set(target["components"]) | set(board["components"])). */
static hal_status_t board_components(jb_json_tree_view_t target,
                                     jb_json_tree_view_t board,
                                     jb_vector_t *out) {
  hal_status_t status = HAL_OK;
  const jb_json_tree_view_t lists[] = {get(target, "components"),
                                       get(board, "components")};
  for (size_t l = 0; status == HAL_OK && l < COUNTOF(lists); ++l)
    for (size_t i = 0; status == HAL_OK && i < jh_json_count(lists[l]); ++i) {
      const jb_json_span_t id = jh_json_key(jh_json_item(lists[l], i));
      if (!jh_list_contains(out, id))
        status = jh_list_push(out, id);
    }
  jh_list_sort(out);
  return status;
}

static hal_status_t copy_list(const jb_vector_t *from, jb_vector_t *to) {
  hal_status_t status = HAL_OK;
  for (size_t i = 0; status == HAL_OK && i < jb_vector_size(from); ++i)
    status = jh_list_push(to, jh_string_span(jh_list_at(from, i)));
  return status;
}

/* The status after text built from status: a storage failure of its own
 * when status was HAL_OK, else the failure recorded already. */
static hal_status_t settle(jh_failure_t *failure, hal_status_t status,
                           hal_status_t emitted) {
  return status != HAL_OK ? status : jh_fail_storage(failure, emitted);
}

hal_status_t jh_board_build_outputs(const jh_board_build_t *build,
                                    jh_board_outputs_t *outputs,
                                    jh_failure_t *failure) {
  if (build == NULL || build->registry == NULL || build->features == NULL ||
      build->requested == NULL || build->checkout_root == NULL ||
      outputs == NULL)
    return jh_fail_arguments(failure);
  const jb_json_tree_view_t target = build->target, board = build->board;
  const jh_board_overrides_t *overrides = build->overrides;
  jb_vector_t normalized = {0}, components = {0}, definitions = {0},
              header_definitions = {0}, cmake_definitions = {0};
  jb_string_t text = {0}, feature_hash = {0}, contract = {0}, globs = {0};
  jb_string_t roots[2] = {{0}, {0}};
  jh_feature_resolution_t resolution;
  jh_feature_resolution_init(&resolution);
  jb_vector_t *lists[] = {&normalized, &components, &definitions,
                          &header_definitions, &cmake_definitions};
  jb_string_t *texts[] = {&text,  &feature_hash, &contract,
                          &globs, &roots[0],     &roots[1]};
  hal_status_t status = HAL_OK;
  for (size_t i = 0; status == HAL_OK && i < COUNTOF(lists); ++i)
    status = jh_fail_storage(failure, jh_list_init(lists[i]));
  for (size_t i = 0; status == HAL_OK && i < COUNTOF(texts); ++i)
    status = jh_fail_storage(failure, text_init(texts[i]));
  if (status == HAL_OK)
    status =
        jh_board_normalize_features(build->requested, &normalized, failure);
  if (status == HAL_OK)
    status = jh_board_resolve_features(build->features, target, &normalized,
                                       &resolution, failure);
  /* feature_contract: the profile and every resolved feature. */
  emit_t contract_text = {&text, status};
  put(&contract_text, "hal.profileId=");
  put_value(&contract_text, get(get(board, "hal"), "profileId"));
  for (size_t i = 0; i < jb_vector_size(&resolution.resolved); ++i) {
    put(&contract_text, "\n");
    put_span(&contract_text,
             jh_string_span(jh_list_at(&resolution.resolved, i)));
    put(&contract_text, "=1");
  }
  emit_t hash = {&feature_hash, contract_text.status};
  if (hash.status == HAL_OK)
    put_sha256_hex(&hash, jh_string_span(&text), 12);
  emit_t symbol = {&contract, hash.status};
  put(&symbol, "jh_board_contract_");
  put_c_symbol(&symbol, text_of(get(target, "id")));
  put(&symbol, "_");
  put_c_symbol(&symbol, text_of(get(board, "id")));
  put(&symbol, "_");
  jb_json_span_t digest = jh_string_span(&feature_hash);
  if (overrides != NULL && overrides->contract_hash.length != 0)
    digest = overrides->contract_hash;
  if (digest.length > 12)
    digest.length = 12;
  put_span(&symbol, digest);
  status = settle(failure, status, symbol.status);
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure, overrides != NULL && overrides->components != NULL
                     ? copy_list(overrides->components, &components)
                     : board_components(target, board, &components));
  if (status == HAL_OK)
    status = jh_fail_storage(failure,
                             board_definitions(target, board, &definitions));
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure,
        copy_list(overrides != NULL && overrides->header_definitions != NULL
                      ? overrides->header_definitions
                      : &definitions,
                  &header_definitions));
  if (status == HAL_OK)
    status = jh_fail_storage(
        failure,
        copy_list(overrides != NULL && overrides->cmake_definitions != NULL
                      ? overrides->cmake_definitions
                      : &definitions,
                  &cmake_definitions));
  if (status == HAL_OK)
    status = input_roots(build, roots, failure);
  emit_t glob_text = {&globs, status};
  for (size_t i = 0; i < 2; ++i) {
    put(&glob_text, i == 0 ? "" : ";");
    put_posix(&glob_text, jh_string_span(&roots[i]));
    put(&glob_text, "/*.json");
  }
  status = settle(failure, status, glob_text.status);
  for (size_t i = 0; status == HAL_OK && i < JH_BOARD_OUTPUT_COUNT; ++i)
    jb_string_clear(&outputs->content[i]);

  /* jh_board_config.cmake */
  emit_t e = {&outputs->content[JH_BOARD_OUTPUT_CMAKE], status};
  const jb_json_tree_view_t target_build = get(target, "build");
  const jb_json_tree_view_t board_build = get(board, "build");
  line(&e, "# Generated by jh board config; do not edit.");
  put_cmake_set(&e, "JH_RESOLVED_TARGET");
  put_value(&e, get(target, "id"));
  line(&e, "\")");
  put_cmake_set(&e, "JH_RESOLVED_BOARD");
  put_value(&e, get(board, "id"));
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_PROVIDER");
  put_value(&e, get(board_build, "provider"));
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_RECIPE");
  put_value(&e, get(target_build, "recipe"));
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_COMPONENTS");
  put_list(&e, &components, ";");
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_COMPILE_DEFINITIONS");
  put_list(&e, &cmake_definitions, ";");
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_EXPECTED_FLASH_BYTES");
  put_value(&e, get(get(get(board, "memory"), "flash"), "expectedBytes"));
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_REQUESTED_FEATURES");
  put_list(&e, &resolution.requested, ";");
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_RESOLVED_FEATURES");
  put_list(&e, &resolution.resolved, ";");
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_RESOLVED_FEATURES_DIGEST");
  put(&e, resolution.digest);
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_FEATURES");
  put_list(&e, &resolution.resolved, ";");
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_INPUT_GLOBS");
  put_span(&e, jh_string_span(&globs));
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_FEATURE_HASH");
  put_span(&e, jh_string_span(&feature_hash));
  line(&e, "\")");
  put_cmake_set(&e, "JH_BOARD_CONTRACT_SYMBOL");
  put_span(&e, jh_string_span(&contract));
  line(&e, "\")");
  jb_json_tree_view_t value = {0};
  if (has(target_build, "platform", &value)) {
    put_cmake_set(&e, "PICO_PLATFORM");
    put_value(&e, value);
    line(&e, "\")");
  }
  if (has(target_build, "idfTarget", &value)) {
    put_cmake_set(&e, "IDF_TARGET");
    put_value(&e, value);
    line(&e, "\")");
  }
  if (has(board_build, "board", &value)) {
    put_cmake_set(&e, "PICO_BOARD");
    put_value(&e, value);
    line(&e, "\")");
  }
  status = settle(failure, status, e.status);

  /* jh_board_config.h */
  e = (emit_t){&outputs->content[JH_BOARD_OUTPUT_HEADER], status};
  line(&e, "#pragma once");
  line(&e, build_banner);
  line(&e, "#include <stdint.h>");
  const jb_vector_t *prelude =
      overrides != NULL ? overrides->header_prelude : NULL;
  for (size_t i = 0; prelude != NULL && i < jb_vector_size(prelude); ++i) {
    put_span(&e, jh_string_span(jh_list_at(prelude, i)));
    end_line(&e);
  }
  status = settle(failure, status, e.status);
  if (status == HAL_OK)
    status = target_facts(&e, target, failure);
  size_t words = 0;
  if (status == HAL_OK)
    status = jh_fail_storage(failure, target_words(target, &words));
  jb_string_t quoted = {0};
  if (status == HAL_OK)
    status = jh_fail_storage(failure, text_init(&quoted));
  emit_t quoted_text = {&quoted, status};
  put(&quoted_text, "\"");
  put_value(&quoted_text, get(target, "id"));
  put(&quoted_text, "\"");
  status = settle(failure, status, quoted_text.status);
  const board_facts_t facts = {build->registry,
                               board,
                               &header_definitions,
                               jh_string_span(&quoted),
                               words,
                               true,
                               true};
  if (status == HAL_OK)
    status = board_facts(&e, &facts, failure);
  jb_string_destroy(&quoted);

  /* The link contract. */
  e = (emit_t){&outputs->content[JH_BOARD_OUTPUT_LINK_HEADER], status};
  line(&e, "#pragma once");
  line(&e, build_banner);
  line(&e, "#ifdef __cplusplus");
  line(&e, "extern \"C\" {");
  line(&e, "#endif");
  put(&e, "void ");
  put_span(&e, jh_string_span(&contract));
  line(&e, "(void);");
  line(&e, "#ifdef __cplusplus");
  line(&e, "}");
  line(&e, "#endif");
  put(&e, "#define JH_BOARD_CONTRACT_SYMBOL ");
  put_span(&e, jh_string_span(&contract));
  end_line(&e);
  e.out = &outputs->content[JH_BOARD_OUTPUT_LINK_DEFINITION];
  line(&e, build_banner);
  line(&e, "#include \"jh_link_contract.h\"");
  line(&e, "void JH_BOARD_CONTRACT_SYMBOL(void) {}");
  e.out = &outputs->content[JH_BOARD_OUTPUT_LINK_REFERENCE];
  line(&e, build_banner);
  line(&e, "#include \"jh_link_contract.h\"");
  line(&e, "#if defined(__GNUC__) || defined(__clang__)");
  line(&e, "#define JH_CONSTRUCTOR_USED __attribute__((constructor, used))");
  line(&e, "static void JH_CONSTRUCTOR_USED jh_require_board_contract(void)");
  line(&e, "{");
  line(&e, "    JH_BOARD_CONTRACT_SYMBOL();");
  line(&e, "}");
  line(&e, "#else");
  line(&e, "typedef void (*jh_board_contract_fn_t)(void);");
  line(&e, "static jh_board_contract_fn_t const jh_board_contract_reference =");
  line(&e, "    &JH_BOARD_CONTRACT_SYMBOL;");
  line(&e, "#endif");
  status = settle(failure, status, e.status);

  /* jh_board_resolved.json and generation.d */
  const resolved_record_t record = {build,
                                    &resolution,
                                    &components,
                                    &cmake_definitions,
                                    jh_string_span(&feature_hash),
                                    jh_string_span(&contract)};
  if (status == HAL_OK)
    status = resolved_json(&record, &outputs->content[JH_BOARD_OUTPUT_RESOLVED],
                           failure);
  e = (emit_t){&outputs->content[JH_BOARD_OUTPUT_DEPENDENCIES], status};
  if (status == HAL_OK)
    status = dependencies(build, roots, &e, failure);

  jh_feature_resolution_destroy(&resolution);
  for (size_t i = 0; i < COUNTOF(texts); ++i)
    jb_string_destroy(texts[i]);
  for (size_t i = 0; i < COUNTOF(lists); ++i)
    jh_list_destroy(lists[i]);
  return status;
}

