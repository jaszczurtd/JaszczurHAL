static int64_t board_flash_bytes(const jh_esp_t *e) {
  int64_t bytes = 0;
  (void)jh_json_int64(
      jh_json_field(jh_json_field(jh_json_field(e->model.board_descriptor->root,
                                                "memory"),
                                  "flash"),
                    "expectedBytes"),
      &bytes);
  return bytes;
}

static void line(jb_string_t *out, hal_status_t *status, const char *text) {
  jh_put(out, status, text);
  jh_put(out, status, "\n");
}

/* _render_sdkconfig_defaults */
const char *esp_sdkconfig_defaults_text(jh_esp_t *e) {
  const jh_esp_model_t *m = &e->model;
  const int64_t flash = board_flash_bytes(e);
  const int64_t mib = 1024 * 1024;
  if (!esp_ok(e))
    return "";
  if (flash <= 0 || flash % mib != 0) {
    char number[32];
    (void)snprintf(number, sizeof number, "%lld", (long long)flash);
    (void)ESP_FAIL(e,
                   jh_span("ESP-IDF board flash size must be a positive "
                           "whole MiB: "),
                   jh_span(number));
    return "";
  }
  jb_string_t out = {0};
  hal_status_t status = jb_string_init(&out, jb_heap_allocator());
  char size[64];
  (void)snprintf(size, sizeof size, "CONFIG_ESPTOOLPY_FLASHSIZE_%lldMB=y",
                 (long long)(flash / mib));
  line(&out, &status, BANNER);
  line(&out, &status, size);
  if (strcmp(m->idf_target, "esp32s3") == 0)
    line(&out, &status, "CONFIG_ESP_CONSOLE_USB_SERIAL_JTAG=y");
  else if (strcmp(m->idf_target, "esp32") == 0)
    line(&out, &status, "CONFIG_ESP_CONSOLE_UART_DEFAULT=y");
  static const struct {
    const char *feature;
    const char *lines[7];
  } rules[] = {
      /* Four HAL TCP sockets, two listeners and four UDP sockets must not
       * consume the entire lwIP descriptor pool; core locking provides the
       * nested stack guard and the raw-netif extension of WireGuard. */
      {"HAL_ENABLE_NETWORK_CORE",
       {"CONFIG_LWIP_MAX_SOCKETS=16", "CONFIG_LWIP_TCPIP_CORE_LOCKING=y"}},
      /* esp_netif keeps its handle in netif->state unless a bridge build moves
       * it to client data; the WireGuard netif owns netif->state. lwIP's
       * thread runs the handshake, which peaked at 3.4 KiB on hardware. */
      {"HAL_ENABLE_WIREGUARD",
       {"CONFIG_ESP_NETIF_BRIDGE_EN=y",
        "CONFIG_LWIP_TCPIP_TASK_STACK_SIZE=6144"}},
      {"HAL_ENABLE_PULSE_CAPTURE", {"CONFIG_MCPWM_ISR_CACHE_SAFE=y"}},
      /* The IRAM-safe continuous ADC interrupt keeps collecting frames
       * through flash operations. */
      {"HAL_ENABLE_ADC_SCAN", {"CONFIG_ADC_CONTINUOUS_ISR_IRAM_SAFE=y"}},
      /* The GPTimer alarm writes the LEDC duty with the flash cache off. */
      {"HAL_ENABLE_DMA_PWM_AUDIO",
       {"CONFIG_GPTIMER_ISR_HANDLER_IN_IRAM=y",
        "CONFIG_LEDC_CTRL_FUNC_IN_IRAM=y"}},
      {"HAL_ENABLE_BLE",
       {"CONFIG_BT_ENABLED=y", "CONFIG_BT_NIMBLE_ENABLED=y",
        "CONFIG_BT_NIMBLE_ROLE_CENTRAL=y", "CONFIG_BT_NIMBLE_ROLE_PERIPHERAL=y",
        "CONFIG_BT_NIMBLE_ROLE_BROADCASTER=y",
        "CONFIG_BT_NIMBLE_ROLE_OBSERVER=y",
        "CONFIG_BT_NIMBLE_MAX_CONNECTIONS=1"}},
      {"HAL_ENABLE_BLUETOOTH_CLASSIC",
       {"CONFIG_BT_ENABLED=y", "CONFIG_BT_BLUEDROID_ENABLED=y",
        "CONFIG_BT_CLASSIC_ENABLED=y", "CONFIG_BTDM_CTRL_MODE_BR_EDR_ONLY=y"}},
      {"HAL_ENABLE_BLUETOOTH_HID_HOST",
       {"CONFIG_BT_HID_ENABLED=y", "CONFIG_BT_HID_HOST_ENABLED=y"}},
      /* OTA stages into the inactive app slot with bootloader rollback. */
      {"HAL_ENABLE_OTA",
       {"CONFIG_PARTITION_TABLE_TWO_OTA_LARGE=y",
        "CONFIG_BOOTLOADER_APP_ROLLBACK_ENABLE=y"}},
      /* ESP-IDF owns task stacks: both FreeRTOS protection layers. */
      {"HAL_ENABLE_STACK_GUARD",
       {"CONFIG_FREERTOS_CHECK_STACKOVERFLOW_CANARY=y",
        "CONFIG_FREERTOS_WATCHPOINT_END_OF_STACK=y"}},
  };
  for (size_t r = 0; r < COUNTOF(rules); ++r) {
    if (!jh_list_contains(&m->resolved, jh_span(rules[r].feature)))
      continue;
    for (size_t i = 0; i < COUNTOF(rules[r].lines) && rules[r].lines[i]; ++i)
      line(&out, &status, rules[r].lines[i]);
  }
  jb_json_tree_view_t psram = {0};
  const jb_json_tree_view_t memory =
      jh_json_field(m->board_descriptor->root, "memory");
  if (jh_json_member(memory, "psram", &psram) &&
      jh_json_type(psram) != JB_JSON_NULL) {
    line(&out, &status, "CONFIG_SPIRAM=y");
    const jb_json_span_t psram_interface =
        jh_build_descriptor_text(psram, "interface", NULL);
    if (jh_span_equal(psram_interface, jh_span("quad")))
      line(&out, &status, "CONFIG_SPIRAM_MODE_QUAD=y");
    else if (jh_span_equal(psram_interface, jh_span("octal")))
      line(&out, &status, "CONFIG_SPIRAM_MODE_OCT=y");
    else {
      jb_string_destroy(&out);
      (void)ESP_FAIL(e, jh_span("Unsupported ESP-IDF PSRAM interface: "),
                     psram_interface);
      return "";
    }
    line(&out, &status, "CONFIG_SPIRAM_SPEED_80M=y");
  }
  (void)esp_storage(e, status);
  const char *result = ESP_TEXT(e, jh_string_span(&out));
  jb_string_destroy(&out);
  return result;
}

