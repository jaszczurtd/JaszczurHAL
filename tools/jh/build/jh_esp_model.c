/* read_text() of a generated file for a comparison: universal newlines. */
static bool read_text(jh_esp_t *e, const char *path, jb_string_t *out) {
  jb_file_data_t data = {0};
  if (!esp_read(e, path, &data))
    return false;
  const bool ok = esp_decode_text(
      e, (jb_json_span_t){(const char *)data.data, data.length}, out);
  jb_file_release(&data);
  return ok;
}

bool esp_validate_board_contract(jh_esp_t *e) {
  const char *generated = esp_join(e, e->build_dir, JH_ESP_GENERATED_DIR);
  jb_temp_dir_t *temporary = NULL;
  jb_vector_t compiler = {0};
  if (!esp_list_init(e, &compiler))
    return false;
  if (esp_storage(e, jb_temp_dir_create(e->build_dir, &temporary)) &&
      (!e->model.device_tree || esp_abi_command(e, &compiler)) &&
      esp_board_inputs(e, jb_temp_dir_path(temporary), &compiler)) {
    const char *const *names =
        e->model.device_tree ? tree_contract_inputs : board_contract_inputs;
    const size_t count = e->model.device_tree ? COUNTOF(tree_contract_inputs)
                                              : COUNTOF(board_contract_inputs);
    for (size_t i = 0; i < count && esp_ok(e); ++i) {
      const char *actual = esp_join(e, generated, names[i]);
      const char *expected = esp_join(e, jb_temp_dir_path(temporary), names[i]);
      if (!esp_is_file(actual)) {
        (void)ESP_FAIL(e,
                       jh_span("Generated board contract input is missing: "),
                       jh_span(actual));
        break;
      }
      jb_file_data_t a = {0}, b = {0};
      if (esp_read(e, actual, &a) && esp_read(e, expected, &b) &&
          (a.length != b.length ||
           (a.length != 0 && memcmp(a.data, b.data, a.length) != 0)))
        (void)ESP_FAIL(e,
                       jh_span("Generated board contract differs from the "
                               "current target/board model: "),
                       jh_span(names[i]));
      jb_file_release(&a);
      jb_file_release(&b);
    }
  }
  if (temporary != NULL && jb_temp_dir_remove(&temporary) != HAL_OK)
    (void)esp_storage(e, HAL_EIO);
  jh_list_destroy(&compiler);
  const char *defaults = esp_join(e, generated, SDKCONFIG_DEFAULTS);
  if (esp_ok(e) && !esp_is_file(defaults))
    return ESP_FAIL(
        e, jh_span("Generated ESP-IDF sdkconfig defaults are missing: "),
        jh_span(defaults));
  jb_string_t actual = {0};
  if (esp_ok(e) &&
      esp_storage(e, jb_string_init(&actual, jb_heap_allocator())) &&
      read_text(e, defaults, &actual) &&
      strcmp(jb_string_data(&actual), esp_sdkconfig_defaults_text(e)) != 0)
    (void)ESP_FAIL(e,
                   jh_span("Generated ESP-IDF sdkconfig defaults differ from "
                           "the current target/board model"));
  jb_string_destroy(&actual);
  return esp_ok(e);
}

jb_json_tree_t *esp_validate_project_contract(jh_esp_t *e,
                                              jb_json_tree_view_t *project) {
  const char *generated = esp_join(e, e->build_dir, JH_ESP_GENERATED_DIR);
  jb_vector_t defaults = {0};
  jb_string_t actual_cmake = {0};
  jb_json_tree_t *actual = NULL, *expected = NULL;
  if (!esp_list_init(e, &defaults) ||
      !esp_storage(e, jb_string_init(&actual_cmake, jb_heap_allocator())) ||
      !esp_sdkconfig_defaults(e, &defaults))
    goto done;
  const char *cmake_path = esp_join(e, generated, PROJECT_CMAKE);
  const char *expected_cmake = project_cmake(e, &defaults);
  if (!esp_ok(e))
    goto done;
  jb_file_data_t data = {0};
  const hal_status_t read = jb_file_read(cmake_path, JH_ESP_MAX_BYTES, &data);
  if (read != HAL_OK) {
    (void)ESP_FAIL(e, jh_span("Cannot read generated ESP-IDF project config "),
                   jh_span(cmake_path), jh_span(": "),
                   jh_span(hal_status_to_string(read)));
    goto done;
  }
  (void)esp_decode_text(
      e, (jb_json_span_t){(const char *)data.data, data.length}, &actual_cmake);
  jb_file_release(&data);
  if (esp_ok(e) && strcmp(jb_string_data(&actual_cmake), expected_cmake) != 0) {
    (void)ESP_FAIL(e, jh_span("Generated ESP-IDF project CMake config differs "
                              "from the current project model"));
    goto done;
  }
  jb_json_tree_view_t root = {0}, wanted = {0};
  actual = esp_load_json(e, esp_join(e, generated, PROJECT_JSON), true, &root);
  const char *contract = project_contract(e, &defaults);
  if (!esp_ok(e))
    goto done;
  /* Python's dict order of the expected contract, for repr(). */
  expected = esp_parse_text(e, jh_span(contract), &wanted);
  if (expected == NULL)
    goto done;
  if (!esp_tree_equal(e, root, wanted)) {
    jb_vector_t keys = {0};
    if (esp_list_init(e, &keys)) {
      for (size_t i = 0; i < jh_json_count(root) && esp_ok(e); ++i)
        (void)esp_push_unique(e, &keys, jh_json_key(jh_json_item(root, i)));
      for (size_t i = 0; i < jh_json_count(wanted) && esp_ok(e); ++i)
        (void)esp_push_unique(e, &keys, jh_json_key(jh_json_item(wanted, i)));
      jh_list_sort(&keys);
      for (size_t i = 0; i < jb_vector_size(&keys) && esp_ok(e); ++i) {
        const char *key = esp_at(&keys, i);
        jb_json_tree_view_t a = {0}, b = {0};
        const bool has_a = jh_json_member(root, key, &a);
        const bool has_b = jh_json_member(wanted, key, &b);
        if (!has_a)
          a = (jb_json_tree_view_t){0};
        if (!has_b)
          b = (jb_json_tree_view_t){0};
        if (esp_tree_equal(e, a, b))
          continue;
        (void)ESP_FAIL(e, jh_span("Generated project config "), jh_span(key),
                       jh_span(" mismatch: expected "), esp_repr_tree(e, b),
                       jh_span(", found "), esp_repr_tree(e, a));
      }
    }
    jh_list_destroy(&keys);
    if (esp_ok(e))
      (void)ESP_FAIL(e, jh_span("Generated project config differs from the "
                                "current model"));
  }
done:
  jb_json_tree_destroy(expected);
  jb_string_destroy(&actual_cmake);
  jh_list_destroy(&defaults);
  if (!esp_ok(e)) {
    jb_json_tree_destroy(actual);
    return NULL;
  }
  *project = (jb_json_tree_view_t){0};
  (void)jb_json_tree_root(actual, project);
  return actual;
}
