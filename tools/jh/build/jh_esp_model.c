/* _cmake_quote */
static bool cmake_quote(jh_esp_t *e, jb_string_t *out, hal_status_t *status,
                        const char *value) {
  if (strpbrk(value, "\n\r;") != NULL)
    return ESP_FAIL(e,
                    jh_span("Value cannot be represented in generated CMake: "),
                    esp_repr(e, jh_span(value)));
  jh_put(out, status, "\"");
  for (const char *c = value; *c != '\0' && *status == HAL_OK; ++c)
    jh_put(out, status,
           *c == '\\'  ? "/"
           : *c == '"' ? "\\\""
                       : (char[2]){*c, 0});
  jh_put(out, status, "\"");
  return true;
}

static bool cmake_set(jh_esp_t *e, jb_string_t *out, hal_status_t *status,
                      const char *name, const char *value) {
  jh_put(out, status, "set(");
  jh_put(out, status, name);
  jh_put(out, status, " ");
  if (!cmake_quote(e, out, status, value))
    return false;
  jh_put(out, status, ")\n");
  return true;
}

/* _render_cmake_list; posix lists hold paths, rendered canonical and in
 * as_posix() form. */
static bool cmake_list(jh_esp_t *e, jb_string_t *out, hal_status_t *status,
                       const char *name, const jb_vector_t *values,
                       const char *root) {
  jh_put(out, status, "set(");
  jh_put(out, status, name);
  jh_put(out, status, "\n");
  for (size_t i = 0; i < jb_vector_size(values) && esp_ok(e); ++i) {
    const char *value = esp_at(values, i);
    if (root != NULL)
      value = esp_posix(
          e, esp_resolve(e, root[0] != '\0' ? esp_join(e, root, value) : value,
                         e->options->base));
    jh_put(out, status, "    ");
    if (!esp_ok(e) || !cmake_quote(e, out, status, value))
      return false;
    jh_put(out, status, "\n");
  }
  jh_put(out, status, ")\n");
  return esp_ok(e);
}

/* _render_project_cmake */
static const char *project_cmake(jh_esp_t *e, const jb_vector_t *defaults) {
  const jh_esp_model_t *m = &e->model;
  jb_string_t out = {0};
  hal_status_t status = jb_string_init(&out, jb_heap_allocator());
  line(&out, &status, BANNER);
  bool ok =
      cmake_set(e, &out, &status, "JH_ESP_IDF_TARGET", m->idf_target) &&
      cmake_set(e, &out, &status, "JH_ESP_IDF_BOARD", m->board) &&
      cmake_set(e, &out, &status, "JH_ESP_IDF_PROJECT_NAME", m->project_name);
  /* The components then name the generated jh_hardware.h for the hook. */
  if (ok && m->device_tree)
    line(&out, &status, "set(JH_ESP_IDF_DEVICE_TREE TRUE)");
  ok = ok && cmake_set(e, &out, &status, "JH_ESP_IDF_PROJECT_DIR",
                       esp_posix(e, m->project_dir));
  if (ok && m->ram_code_sources != NULL)
    ok = cmake_set(e, &out, &status, "JH_ESP_IDF_RAM_CODE_SOURCES",
                   m->ram_code_sources);
  ok = ok &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_PROJECT_SOURCES",
                  &m->project_sources, "") &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_PROJECT_INCLUDE_DIRS",
                  &m->project_include_dirs, "") &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_PROJECT_EXTRA_INCLUDE_DIRS",
                  &m->extra_include_dirs, "") &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_PROJECT_LINK_LIBRARIES",
                  &m->link_libraries, "") &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_COMPILE_DEFINITIONS",
                  &m->compile_definitions, NULL) &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_RESOLVED_FEATURES",
                  &m->resolved, NULL) &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_COMPONENT_SOURCES",
                  &m->integration_sources, e->repo_root) &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_COMPONENT_INCLUDE_DIRS",
                  &m->component_include_dirs, e->repo_root) &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_COMPONENT_REQUIRES",
                  &m->component_dependencies, NULL) &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_COMPONENT_PRIV_REQUIRES",
                  &m->private_dependencies, NULL) &&
       cmake_list(e, &out, &status, "JH_ESP_IDF_SDKCONFIG_DEFAULTS", defaults,
                  "");
  (void)ok;
  (void)esp_storage(e, status);
  const char *result = esp_ok(e) ? ESP_TEXT(e, jh_string_span(&out)) : "";
  jb_string_destroy(&out);
  return result;
}

/* _project_input_digest */
static const char *input_digest(jh_esp_t *e, const char *path,
                                const char *display) {
  if (!esp_ok(e))
    return "";
  if (!esp_is_file(path)) {
    (void)ESP_FAIL(e, jh_span("Project "), jh_span(display),
                   jh_span(" is missing: "), jh_span(path));
    return "";
  }
  char digest[65] = {0};
  if (!esp_sha256_file(e, path, digest))
    return "";
  return ESP_TEXT(e, jh_span(digest));
}

/* _display_path */
static const char *display_path(jh_esp_t *e, const char *path) {
  const char *relative = esp_relative(e, path, e->model.project_dir);
  return relative != NULL ? relative : esp_posix(e, path);
}

/* _project_config_contract as compact JSON in the runner's key order. */
static const char *project_contract(jh_esp_t *e, const jb_vector_t *defaults) {
  const jh_esp_model_t *m = &e->model;
  jb_vector_t sources = {0}, source_digests = {0}, default_names = {0},
              default_digests = {0};
  esp_json_t json;
  const char *result = "";
  if (!esp_list_init(e, &sources) || !esp_list_init(e, &source_digests) ||
      !esp_list_init(e, &default_names) || !esp_list_init(e, &default_digests))
    goto done;
  for (size_t i = 0; i < jb_vector_size(&m->project_sources) && esp_ok(e);
       ++i) {
    const char *path = esp_at(&m->project_sources, i);
    const char *relative = esp_relative(e, path, m->project_dir);
    if (relative == NULL) {
      (void)ESP_FAIL(e, jh_span("Project input escapes "),
                     jh_span(m->project_dir), jh_span(": "), jh_span(path));
      break;
    }
    (void)esp_push(e, &sources, jh_span(relative));
    (void)esp_push(e, &source_digests,
                   jh_span(input_digest(e, path, "source")));
  }
  for (size_t i = 0; i < jb_vector_size(defaults) && esp_ok(e); ++i) {
    const char *path = esp_at(defaults, i);
    const char *relative = esp_relative(e, path, m->project_dir);
    if (relative == NULL)
      relative = esp_relative(e, path, e->build_dir);
    (void)esp_push(e, &default_names,
                   jh_span(relative != NULL ? relative : path));
    (void)esp_push(e, &default_digests,
                   jh_span(input_digest(e, path, "sdkconfig defaults")));
  }
  const char *header = esp_join(e, m->config_dir, "hal_project_config.h");
  const bool has_header = esp_is_file(header);
  const char *header_path = has_header ? display_path(e, header) : "";
  const char *header_digest =
      has_header ? input_digest(e, header, "configuration header") : "";
  if (!esp_ok(e) || !esp_json_begin(e, &json))
    goto done;
  esp_json_u64(&json, "schemaVersion", 3);
  esp_json_string(&json, "target", jh_span(m->target));
  esp_json_string(&json, "board", jh_span(m->board));
  esp_json_string(&json, "idfTarget", jh_span(m->idf_target));
  esp_json_string(&json, "projectName", jh_span(m->project_name));
  esp_json_list(&json, "projectSources", &sources);
  esp_json_object(&json, "projectSourceSha256");
  for (size_t i = 0; i < jb_vector_size(&sources); ++i)
    esp_json_string(&json, esp_at(&sources, i),
                    jh_string_span(jh_list_at(&source_digests, i)));
  esp_json_object_end(&json);
  esp_json_array(&json, "projectIncludeDirs");
  for (size_t i = 0; i < jb_vector_size(&m->project_include_dirs) && esp_ok(e);
       ++i)
    esp_json_string(
        &json, NULL,
        jh_span(display_path(e, esp_at(&m->project_include_dirs, i))));
  esp_json_array_end(&json);
  if (has_header) {
    esp_json_object(&json, "projectConfigHeader");
    esp_json_string(&json, "path", jh_span(header_path));
    esp_json_string(&json, "sha256", jh_span(header_digest));
    esp_json_object_end(&json);
  } else
    esp_json_null(&json, "projectConfigHeader");
  esp_json_array(&json, "projectExtraIncludeDirs");
  for (size_t i = 0; i < jb_vector_size(&m->extra_include_dirs) && esp_ok(e);
       ++i)
    esp_json_string(
        &json, NULL,
        jh_span(display_path(e, esp_at(&m->extra_include_dirs, i))));
  esp_json_array_end(&json);
  /* Precompiled archives; their content decides the image too. */
  esp_json_array(&json, "projectLinkLibraries");
  for (size_t i = 0; i < jb_vector_size(&m->link_libraries) && esp_ok(e); ++i) {
    const char *path = esp_at(&m->link_libraries, i);
    esp_json_object(&json, NULL);
    esp_json_string(&json, "path", jh_span(display_path(e, path)));
    esp_json_string(&json, "sha256",
                    jh_span(input_digest(e, path, "link library")));
    esp_json_object_end(&json);
  }
  esp_json_array_end(&json);
  esp_json_list(&json, "requestedFeatures", &m->requested);
  esp_json_list(&json, "compileDefinitions", &m->compile_definitions);
  esp_json_list(&json, "sdkconfigDefaults", &default_names);
  esp_json_object(&json, "sdkconfigDefaultSha256");
  for (size_t i = 0; i < jb_vector_size(&default_names); ++i)
    esp_json_string(&json, esp_at(&default_names, i),
                    jh_string_span(jh_list_at(&default_digests, i)));
  esp_json_object_end(&json);
  esp_json_end(&json);
  if (esp_storage(e, json.status))
    result = ESP_TEXT(e, jh_string_span(&json.text));
  jb_string_destroy(&json.text);
done:
  jh_list_destroy(&default_digests);
  jh_list_destroy(&default_names);
  jh_list_destroy(&source_digests);
  jh_list_destroy(&sources);
  return result;
}

/* _discard_stale_sdkconfig */
static bool discard_stale_sdkconfig(jh_esp_t *e, const char *generated,
                                    const jb_vector_t *defaults) {
  jb_sha256_context_t sha;
  jb_sha256_init(&sha);
  const uint8_t zero = 0;
  for (size_t i = 0; i < jb_vector_size(defaults) && esp_ok(e); ++i) {
    const char *path = esp_at(defaults, i);
    const char *posix = esp_posix(e, esp_resolve(e, path, e->options->base));
    jb_file_data_t data = {0};
    if (!esp_read(e, path, &data))
      break;
    jb_sha256_update(&sha, (const uint8_t *)posix, strlen(posix));
    jb_sha256_update(&sha, &zero, 1);
    if (data.length != 0)
      jb_sha256_update(&sha, data.data, data.length);
    jb_sha256_update(&sha, &zero, 1);
    jb_file_release(&data);
  }
  if (!esp_ok(e))
    return false;
  uint8_t digest[JB_SHA256_DIGEST_BYTES];
  jb_sha256_final(&sha, digest);
  char current[65] = {0};
  jh_sha256_hex(digest, current);
  const char *stamp = esp_join(e, generated, SDKCONFIG_STAMP);
  jb_json_span_t previous = {"", 0};
  jb_file_data_t data = {0};
  if (esp_is_file(stamp) && esp_read(e, stamp, &data))
    previous =
        esp_strip((jb_json_span_t){(const char *)data.data, data.length});
  const bool changed = !jh_span_equal(previous, jh_span(current));
  jb_file_release(&data);
  const char *sdkconfig = esp_join(e, e->build_dir, "sdkconfig");
  if (esp_ok(e) && changed && esp_exists(sdkconfig))
    (void)esp_remove(e, sdkconfig);
  return esp_write_text(e, stamp,
                        jh_span(ESP_TEXT(e, jh_span(current), jh_span("\n"))));
}

/* configured_abi_command */
static bool configured_abi_command(jh_esp_t *e, jb_vector_t *command) {
  if (!e->model.device_tree ||
      !esp_is_file(esp_join(e, e->build_dir, "compile_commands.json")))
    return esp_ok(e);
  jh_failure_t ignored;
  jh_failure_init(&ignored);
  jh_failure_t *saved = e->failure;
  e->failure = &ignored;
  (void)esp_abi_command(e, command);
  e->failure = saved;
  const bool memory = ignored.status == HAL_ENOMEM;
  if (ignored.status != HAL_OK) {
    jh_list_destroy(command);
    (void)jh_list_init(command);
  }
  jh_failure_destroy(&ignored);
  return memory ? esp_storage(e, HAL_ENOMEM) : esp_ok(e);
}

bool esp_materialize(jh_esp_t *e) {
  const char *generated = esp_join(e, e->build_dir, JH_ESP_GENERATED_DIR);
  jb_vector_t compiler = {0}, defaults = {0};
  if (!esp_list_init(e, &compiler) || !esp_list_init(e, &defaults))
    goto done;
  const hal_status_t made = jb_fs_mkdir(generated, true);
  if (made != HAL_OK) {
    (void)jh_fail(e->failure, made, 1,
                  JH_PARTS(jh_span("cannot create "), jh_span(generated)));
    goto done;
  }
  if (!configured_abi_command(e, &compiler) ||
      !esp_board_inputs(e, generated, &compiler))
    goto done;
  const char *text = esp_sdkconfig_defaults_text(e);
  if (!esp_write_text(e, esp_join(e, generated, SDKCONFIG_DEFAULTS),
                      jh_span(text)) ||
      !esp_sdkconfig_defaults(e, &defaults) ||
      !discard_stale_sdkconfig(e, generated, &defaults))
    goto done;
  const char *cmake = project_cmake(e, &defaults);
  if (!esp_write_text(e, esp_join(e, generated, PROJECT_CMAKE), jh_span(cmake)))
    goto done;
  const char *contract = project_contract(e, &defaults);
  if (esp_ok(e))
    (void)esp_write_text(e, esp_join(e, generated, PROJECT_JSON),
                         jh_span(esp_dumps(e, jh_span(contract))));
done:
  jh_list_destroy(&defaults);
  jh_list_destroy(&compiler);
  return esp_ok(e);
}

/* The failure of a jh hardware command for a generated file, as
 * generation_failure of the CLI words it. */
static void generation_failure(jh_esp_t *e, const char *path) {
  if (!esp_ok(e) && e->failure->exit_code != 4)
    (void)jh_fail_pointer(e->failure, "JH-HW-GENERATION", jh_span(path),
                          jh_span(""),
                          JH_PARTS(jh_string_span(&e->failure->message)));
}

/* write_model and finalize of device_tree_project.py through the C API of
 * jh hardware finalize. */
static bool tree_inputs(jh_esp_t *e, const char *directory,
                        const jb_vector_t *compiler) {
  const jh_esp_model_t *m = &e->model;
  const char *resolved = esp_join(e, directory, "jh_hardware_resolved.json");
  const char *header = esp_join(e, directory, "jh_hardware.h");
  bool changed = false;
  if (!esp_ok(e) ||
      jh_write_generated(resolved, jh_span(m->document), &changed,
                         e->failure) != HAL_OK ||
      jh_write_generated(header, jh_span(m->header), &changed, e->failure) !=
          HAL_OK)
    return false;
  jb_string_t output = {0};
  jb_vector_t flags = {0};
  jh_hardware_outputs_t outputs;
  jh_hardware_outputs_init(&outputs);
  const char *paths[JH_HARDWARE_OUTPUT_COUNT] = {0};
  bool managed = false;
  if (!esp_storage(e, jb_string_init(&output, jb_heap_allocator())) ||
      !esp_list_init(e, &flags))
    goto done;
  if (jh_board_managed_output(directory, esp_parent(e, directory), e->repo_root,
                              &output, e->failure) != HAL_OK) {
    generation_failure(e, directory);
    goto done;
  }
  managed = true;
  for (size_t i = 0; i < JH_HARDWARE_OUTPUT_COUNT; ++i)
    paths[i] =
        esp_join(e, jb_string_data(&output), jh_hardware_output_names[i]);
  for (size_t i = 1; i < jb_vector_size(compiler) && esp_ok(e); ++i)
    (void)esp_push(e, &flags, jh_string_span(jh_list_at(compiler, i)));
  const jh_hardware_build_options_t options = {
      &e->hardware,
      &e->hardware.feature_registry,
      m->config_dir,
      esp_resolve(e, resolved, e->options->base),
      esp_resolve(e, header, e->options->base),
      jb_string_data(&output),
      m->variant,
      jb_vector_size(compiler) != 0 ? esp_at(compiler, 0) : NULL,
      &m->tree_definitions,
      &flags};
  if (!esp_ok(e) ||
      jh_hardware_finalize(&options, &outputs, e->failure) != HAL_OK)
    goto done;
  for (size_t i = 0; i < JH_HARDWARE_OUTPUT_COUNT && esp_ok(e); ++i)
    if (jh_project_build_write(paths[i], jh_string_span(&outputs.content[i]),
                               &changed, e->failure) != HAL_OK)
      generation_failure(e, paths[i]);
done:
  if (!esp_ok(e) && managed)
    for (size_t i = 0; i < JH_HARDWARE_OUTPUT_COUNT; ++i)
      if (paths[i] != NULL && paths[i][0] != '\0')
        (void)jb_fs_remove(paths[i], false);
  jh_hardware_outputs_destroy(&outputs);
  jh_list_destroy(&flags);
  jb_string_destroy(&output);
  return esp_ok(e);
}

bool esp_board_inputs(jh_esp_t *e, const char *directory,
                      const jb_vector_t *compiler) {
  const jh_esp_model_t *m = &e->model;
  /* Files of the other path are removed. */
  if (m->device_tree) {
    static const char *const stale[] = {"jh_board_resolved.json",
                                        "jh_board_config.cmake"};
    for (size_t i = 0; i < COUNTOF(stale) && esp_ok(e); ++i)
      (void)esp_remove(e, esp_join(e, directory, stale[i]));
    return esp_ok(e) && tree_inputs(e, directory, compiler);
  }
  static const char *const stale[] = {
      "jh_hardware.h", "jh_hardware_resolved.json", "jh_hardware_config.json",
      "jh_hardware_package.cmake", "jh_hardware_config.cmake"};
  for (size_t i = 0; i < COUNTOF(stale) && esp_ok(e); ++i)
    (void)esp_remove(e, esp_join(e, directory, stale[i]));
  jh_board_outputs_t outputs = {0};
  size_t changed = 0;
  if (esp_ok(e) && esp_storage(e, jh_board_outputs_init(&outputs))) {
    const jh_board_build_t build = {&e->boards,
                                    &e->features,
                                    m->target_descriptor->root,
                                    m->board_descriptor->root,
                                    &m->requested,
                                    e->repo_root,
                                    NULL};
    if (jh_board_build_outputs(&build, &outputs, e->failure) == HAL_OK)
      (void)jh_board_write_outputs(&outputs, directory, &changed, e->failure);
  }
  jh_board_outputs_destroy(&outputs);
  return esp_ok(e);
}

