#ifndef _WIN32
/* shlex.split(command) in POSIX mode. */
static bool split_command(jh_esp_t *e, const char *command, jb_vector_t *out) {
  jb_string_t token = {0};
  if (!esp_storage(e, jb_string_init(&token, jb_heap_allocator())))
    return false;
  hal_status_t status = HAL_OK;
  bool active = false;
  const char *c = command;
  while (*c != '\0' && status == HAL_OK && esp_ok(e)) {
    if (*c == ' ' || *c == '\t' || *c == '\n' || *c == '\r') {
      if (active)
        (void)esp_push(e, out, jh_string_span(&token));
      jb_string_clear(&token);
      active = false;
      ++c;
    } else if (*c == '\\') {
      if (c[1] == '\0') {
        (void)ESP_FAIL(e, jh_span("No escaped character"));
        break;
      }
      status = jb_string_append(&token, c + 1, 1);
      active = true;
      c += 2;
    } else if (*c == '\'') {
      const char *end = strchr(c + 1, '\'');
      if (end == NULL) {
        (void)ESP_FAIL(e, jh_span("No closing quotation"));
        break;
      }
      status = jb_string_append(&token, c + 1, (size_t)(end - c - 1));
      active = true;
      c = end + 1;
    } else if (*c == '"') {
      ++c;
      while (*c != '"' && *c != '\0' && status == HAL_OK) {
        if (*c == '\\' && (c[1] == '"' || c[1] == '\\'))
          ++c;
        status = jb_string_append(&token, c, 1);
        ++c;
      }
      if (*c != '"') {
        (void)ESP_FAIL(e, jh_span("No closing quotation"));
        break;
      }
      active = true;
      ++c;
    } else {
      status = jb_string_append(&token, c, 1);
      active = true;
      ++c;
    }
  }
  if (esp_storage(e, status) && active)
    (void)esp_push(e, out, jh_string_span(&token));
  jb_string_destroy(&token);
  return esp_ok(e);
}
#else
/* CommandLineToArgvW, as the runner split the command on Windows. */
static bool split_command(jh_esp_t *e, const char *command, jb_vector_t *out) {
  const int wide = MultiByteToWideChar(CP_UTF8, 0, command, -1, NULL, 0);
  if (wide <= 0)
    return ESP_FAIL(e, jh_span("compile command is not valid UTF-8"));
  wchar_t *text = malloc(sizeof(wchar_t) * (size_t)wide);
  if (text == NULL)
    return esp_storage(e, HAL_ENOMEM);
  (void)MultiByteToWideChar(CP_UTF8, 0, command, -1, text, wide);
  int count = 0;
  LPWSTR *argv = CommandLineToArgvW(text, &count);
  free(text);
  if (argv == NULL)
    return esp_storage(e, HAL_ENOMEM);
  for (int i = 0; i < count && esp_ok(e); ++i) {
    const int bytes =
        WideCharToMultiByte(CP_UTF8, 0, argv[i], -1, NULL, 0, NULL, NULL);
    char *item = bytes > 0 ? malloc((size_t)bytes) : NULL;
    if (item == NULL) {
      (void)esp_storage(e, HAL_ENOMEM);
      break;
    }
    (void)WideCharToMultiByte(CP_UTF8, 0, argv[i], -1, item, bytes, NULL, NULL);
    (void)esp_push(e, out, jh_span(item));
    free(item);
  }
  LocalFree(argv);
  return esp_ok(e);
}
#endif

static bool listed(const char *const *list, size_t count, const char *text) {
  for (size_t i = 0; i < count; ++i)
    if (strcmp(list[i], text) == 0)
      return true;
  return false;
}

bool esp_abi_command(jh_esp_t *e, jb_vector_t *command) {
  static const char *const file_options[] = {
      "-o", "-MF",      "-MT",      "-MQ",      "-I",      "-D",
      "-U", "-include", "-imacros", "-isystem", "-iquote", "-idirafter"};
  static const char *const step_options[] = {"-c",  "-S",  "-E",   "-M",
                                             "-MM", "-MD", "-MMD", "-MP"};
  static const char *const joined[] = {"-o", "-I", "-D", "-U"};
  const char *database = esp_join(e, e->build_dir, "compile_commands.json");
  const char *source =
      esp_resolve(e,
                  esp_join(e, esp_join(e, e->build_dir, JH_ESP_GENERATED_DIR),
                           "jh_link_contract_definition.c"),
                  e->options->base);
  jh_json_location_t where;
  jh_json_location_init(&where);
  jh_failure_t error;
  jh_failure_init(&error);
  jb_json_tree_t *tree = NULL;
  jb_vector_t arguments = {0};
  bool found = false;
  if (!esp_ok(e) || !esp_list_init(e, &arguments))
    goto done;
  if (jh_json_read_value(&where, database, JH_ESP_MAX_BYTES, &tree, &error) !=
      HAL_OK) {
    (void)ESP_FAIL(e, jh_span("Cannot read "), jh_span(database), jh_span(": "),
                   jh_string_span(&error.message));
    goto done;
  }
  jb_json_tree_view_t entries = {0};
  (void)jb_json_tree_root(tree, &entries);
  if (jh_json_type(entries) != JB_JSON_ARRAY)
    entries = (jb_json_tree_view_t){0};
  for (size_t i = 0; i < jh_json_count(entries) && esp_ok(e) && !found; ++i) {
    const jb_json_tree_view_t entry = jh_json_item(entries, i);
    bool has_directory = false;
    const jb_json_span_t text =
        esp_field_text(entry, "directory", &has_directory);
    const char *directory = has_directory ? ESP_TEXT(e, text) : e->build_dir;
    const char *file = ESP_TEXT(e, esp_field_text(entry, "file", NULL));
    if (strcmp(esp_resolve(e, esp_join(e, directory, file), e->options->base),
               source) != 0)
      continue;
    found = true;
    jh_list_destroy(&arguments);
    (void)jh_list_init(&arguments);
    const jb_json_tree_view_t listed_arguments =
        jh_json_field(entry, "arguments");
    if (jh_json_count(listed_arguments) != 0)
      (void)descriptor_strings(e, listed_arguments, &arguments);
    else
      (void)split_command(
          e, ESP_TEXT(e, esp_field_text(entry, "command", NULL)), &arguments);
    size_t first = 0;
    if (jb_vector_size(&arguments) != 0) {
      const jb_json_span_t stem =
          jh_span_path_stem(jh_span(esp_at(&arguments, 0)));
      if (jh_span_equal(stem, jh_span("ccache")) ||
          jh_span_equal(stem, jh_span("sccache")))
        first = 1;
    }
    if (first < jb_vector_size(&arguments))
      (void)esp_push(e, command, jh_span(esp_at(&arguments, first)));
    bool skip = false;
    for (size_t j = first + 1; j < jb_vector_size(&arguments) && esp_ok(e);
         ++j) {
      const char *argument = esp_at(&arguments, j);
      bool prefixed = false;
      for (size_t k = 0; k < COUNTOF(joined); ++k)
        prefixed = prefixed || strncmp(argument, joined[k], 2) == 0;
      if (skip)
        skip = false;
      else if (listed(file_options, COUNTOF(file_options), argument))
        skip = true;
      else if (listed(step_options, COUNTOF(step_options), argument) ||
               prefixed)
        continue;
      else if (strcmp(esp_resolve(e, esp_join(e, directory, argument),
                                  e->options->base),
                      source) == 0)
        continue;
      else if (argument[0] == '@')
        (void)esp_push(
            e, command,
            jh_span(ESP_TEXT(e, jh_span("@"),
                             jh_span(esp_join(e, directory, argument + 1)))));
      else
        (void)esp_push(e, command, jh_span(argument));
    }
  }
  if (esp_ok(e) && !found)
    (void)ESP_FAIL(e, jh_span(database),
                   jh_span(" has no compile command for "), jh_span(source));
done:
  jh_list_destroy(&arguments);
  jb_json_tree_destroy(tree);
  jh_failure_destroy(&error);
  jh_json_location_destroy(&where);
  return esp_ok(e);
}

