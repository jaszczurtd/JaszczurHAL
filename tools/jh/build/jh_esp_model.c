bool esp_load_tables(jh_esp_t *e) {
  const char *path =
      esp_join(e, e->repo_root, "config/tooling/esp_idf_components.json");
  e->tables = esp_load_json(e, path, true, &e->tables_root);
  int64_t version = 0;
  if (esp_ok(e) &&
      (!jh_json_int64(jh_json_field(e->tables_root, "schemaVersion"),
                      &version) ||
       version != 1))
    (void)ESP_FAIL(e, jh_span(path), jh_span(": schemaVersion must be 1"));
  return esp_ok(e);
}

jb_json_tree_view_t esp_table(jh_esp_t *e, const char *key) {
  return jh_json_field(e->tables_root, key);
}

/* The strings of a table array (a missing one has none). */
static bool table_strings(jh_esp_t *e, jb_json_tree_view_t array,
                          jb_vector_t *out, bool unique) {
  for (size_t i = 0; i < jh_json_count(array) && esp_ok(e); ++i) {
    jb_json_span_t text = {"", 0};
    if (!jh_json_string(jh_json_item(array, i), &text))
      return ESP_FAIL(e, jh_span("esp_idf_components.json: tables must hold "
                                 "strings"));
    (void)(unique ? esp_push_unique(e, out, text) : esp_push(e, out, text));
  }
  return esp_ok(e);
}

/* The member names of a table object in code point order. */
static bool table_keys(jh_esp_t *e, jb_json_tree_view_t object,
                       jb_vector_t *out) {
  for (size_t i = 0; i < jh_json_count(object) && esp_ok(e); ++i)
    (void)esp_push(e, out, jh_json_key(jh_json_item(object, i)));
  jh_list_sort(out);
  return esp_ok(e);
}

