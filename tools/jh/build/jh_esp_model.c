static bool name_character(char c) {
  return jh_ascii_is_upper(c) || jh_ascii_is_lower(c) || jh_ascii_is_digit(c) ||
         c == '_' || c == '-';
}

static bool project_name_valid(const char *name) {
  if (!(jh_ascii_is_upper(name[0]) || jh_ascii_is_lower(name[0]) ||
        name[0] == '_'))
    return false;
  for (const char *c = name + 1; *c != '\0'; ++c)
    if (!name_character(*c))
      return false;
  return true;
}

bool esp_project_name(jh_esp_t *e, const char *project_dir, const char **out) {
  const char *name = e->options->name;
  if (name[0] == '\0') {
    /* re.sub(r"[^A-Za-z0-9_-]", "_", name): one "_" per code point. */
    jb_string_t text = {0};
    hal_status_t status = jb_string_init(&text, jb_heap_allocator());
    const char *base = esp_name(project_dir);
    for (const char *c = base; *c != '\0' && status == HAL_OK;) {
      if (name_character(*c)) {
        status = jb_string_append(&text, c, 1);
        ++c;
        continue;
      }
      status = jh_append(&text, "_");
      ++c;
      while (((unsigned char)*c & 0xC0u) == 0x80u)
        ++c;
    }
    if (!esp_storage(e, status)) {
      jb_string_destroy(&text);
      return false;
    }
    const char *first = jb_string_data(&text);
    name = (first[0] == '\0' || jh_ascii_is_digit(first[0]) || first[0] == '-')
               ? ESP_TEXT(e, jh_span("jh_"), jh_string_span(&text))
               : ESP_TEXT(e, jh_string_span(&text));
    jb_string_destroy(&text);
  }
  if (esp_ok(e) && !project_name_valid(name))
    (void)ESP_FAIL(e, jh_span("Invalid ESP-IDF project name: "),
                   esp_repr(e, jh_span(name)));
  *out = name;
  return esp_ok(e);
}

/* Path.suffix of name. */
static jb_json_span_t suffix(const char *name) {
  const char *dot = strrchr(name, '.');
  const size_t length = strlen(name);
  if (dot == NULL || dot == name || (size_t)(dot - name) == length - 1)
    return jh_span("");
  return jh_span(dot);
}

static bool source_suffix(const char *name) {
  const jb_json_span_t value = suffix(name);
  for (size_t i = 0; i < COUNTOF(source_suffixes); ++i)
    if (jh_span_equal(value, jh_span(source_suffixes[i])))
      return true;
  return false;
}

typedef struct {
  jh_esp_t *e;
  jb_vector_t *candidates;
} collect_t;

static hal_status_t collect_source(void *user, const char *path,
                                   jb_json_span_t relative, const char *name) {
  collect_t *collect = user;
  (void)relative;
  if (source_suffix(name))
    (void)esp_push(collect->e, collect->candidates, jh_span(path));
  return collect->e->failure->status;
}

static hal_status_t collect_entry(void *user, const char *name,
                                  const jb_fs_info_t *info) {
  collect_t *collect = user;
  (void)info;
  (void)esp_push(collect->e, collect->candidates, jh_span(name));
  return collect->e->failure->status;
}

/* Order of two paths by their as_posix() form. */
static int compare_posix(const void *left, const void *right) {
  const unsigned char *a = (const unsigned char *)jb_string_data(left);
  const unsigned char *b = (const unsigned char *)jb_string_data(right);
  for (;; ++a, ++b) {
#ifdef _WIN32
    const unsigned char x = *a == '\\' ? '/' : *a, y = *b == '\\' ? '/' : *b;
#else
    const unsigned char x = *a, y = *b;
#endif
    if (x != y || x == '\0')
      return (int)x - (int)y;
  }
}

/* resolve_project_sources: the requested sources, or the C, C++ and assembly
 * files of the project directory and below its src/, sorted. */
static bool project_sources(jh_esp_t *e, const char *project_dir) {
  jb_vector_t candidates = {0}, names = {0}, sorted = {0};
  if (!esp_list_init(e, &candidates) || !esp_list_init(e, &names) ||
      !esp_list_init(e, &sorted))
    goto done;
  const jb_vector_t *requested = e->options->sources;
  collect_t collect = {e, &candidates};
  if (jb_vector_size(requested) != 0) {
    for (size_t i = 0; i < jb_vector_size(requested) && esp_ok(e); ++i) {
      const char *item = esp_at(requested, i);
      (void)esp_push(
          e, &candidates,
          jh_span(esp_absolute(item) ? item : esp_join(e, project_dir, item)));
    }
  } else {
    collect_t listing = {e, &names};
    (void)esp_storage(e, jb_fs_list(project_dir, collect_entry, &listing));
    for (size_t i = 0; i < jb_vector_size(&names) && esp_ok(e); ++i) {
      const char *path = esp_join(e, project_dir, esp_at(&names, i));
      if (esp_is_file(path) && source_suffix(esp_at(&names, i)))
        (void)esp_push(e, &candidates, jh_span(path));
    }
    const char *source_root = esp_join(e, project_dir, "src");
    if (esp_ok(e) && esp_is_dir(source_root))
      (void)jh_walk_files(source_root, jh_span(""), collect_source, &collect,
                          e->failure);
  }
  for (size_t i = 0; i < jb_vector_size(&candidates) && esp_ok(e); ++i) {
    const char *source =
        esp_resolve(e, esp_at(&candidates, i), e->options->base);
    if (!esp_ok(e))
      break;
    if (esp_relative(e, source, project_dir) == NULL)
      (void)ESP_FAIL(e, jh_span("Project input escapes "), jh_span(project_dir),
                     jh_span(": "), jh_span(source));
    else if (!esp_is_file(source))
      (void)ESP_FAIL(e, jh_span("Project source does not exist: "),
                     jh_span(source));
    else if (!source_suffix(esp_name(source)))
      (void)ESP_FAIL(e, jh_span("Unsupported project source suffix: "),
                     jh_span(source));
    else
      (void)esp_push_unique(e, &sorted, jh_span(source));
  }
  if (!esp_ok(e))
    goto done;
  /* sorted(..., key=as_posix) */
  for (size_t i = 0; i < jb_vector_size(&sorted) && esp_ok(e); ++i)
    (void)esp_push(e, &e->model.project_sources,
                   jh_string_span(jh_list_at(&sorted, i)));
  jb_vector_t *list = &e->model.project_sources;
  if (jb_vector_size(list) > 1)
    qsort(jb_vector_data(list), jb_vector_size(list), sizeof(jb_string_t),
          compare_posix);
  if (esp_ok(e) && jb_vector_size(list) == 0)
    (void)ESP_FAIL(e, jh_span("No C/C++/assembly sources found in "),
                   jh_span(project_dir), jh_span("; use --source"));
done:
  jh_list_destroy(&sorted);
  jh_list_destroy(&names);
  jh_list_destroy(&candidates);
  return esp_ok(e);
}

/* _normalize_definition */
static const char *normalize_definition(jh_esp_t *e, const char *value) {
  jb_json_span_t text = esp_strip(jh_span(value));
  if (text.length >= 2 && text.data[0] == '-' && text.data[1] == 'D') {
    text.data += 2;
    text.length -= 2;
  }
  const char *definition = ESP_TEXT(e, text);
  if (!esp_ok(e))
    return "";
  const jb_json_span_t repr = esp_repr(e, jh_span(value));
  if (definition[0] == '\0' || strpbrk(definition, "\n\r;") != NULL) {
    (void)ESP_FAIL(e, jh_span("Invalid compile definition: "), repr);
    return "";
  }
  const char *equal = strchr(definition, '=');
  const size_t name_length =
      equal != NULL ? (size_t)(equal - definition) : strlen(definition);
  bool valid = name_length != 0 && !jh_ascii_is_digit(definition[0]);
  for (size_t i = 0; valid && i < name_length; ++i)
    valid = name_character(definition[i]) && definition[i] != '-';
  if (!valid) {
    (void)ESP_FAIL(e, jh_span("Invalid compile definition name: "), repr);
    return "";
  }
  if (equal != NULL && equal[1] == '\0') {
    (void)ESP_FAIL(e, jh_span("Compile definition has an empty value: "), repr);
    return "";
  }
  if (strstr(definition, "$<") != NULL) {
    (void)ESP_FAIL(e, jh_span("CMake generator expressions are not supported"));
    return "";
  }
  const jb_json_span_t name = {definition, name_length};
  static const char *const owned[] = {"HAL_TARGET_", "HAL_BOARD_PROFILE_",
                                      "JH_ESP_IDF_"};
  for (size_t i = 0; i < COUNTOF(owned); ++i)
    if (strncmp(definition, owned[i], strlen(owned[i])) == 0) {
      (void)ESP_FAIL(e, jh_span("The ESP-IDF dispatcher owns "), name);
      return "";
    }
  if (jh_span_equal(name, jh_span("HAL_PROVIDE_APP_ENTRY"))) {
    (void)ESP_FAIL(
        e, jh_span("The ESP-IDF dispatcher owns HAL_PROVIDE_APP_ENTRY"));
    return "";
  }
  return definition;
}

static const jh_feature_t *feature(const jh_esp_t *e, jb_json_span_t name) {
  const jb_vector_t *features = &e->features.features;
  size_t low = 0, high = jb_vector_size(features);
  while (low < high) {
    const size_t middle = low + (high - low) / 2;
    const jh_feature_t *item = jb_vector_const_at(features, middle);
    const int order = jh_span_compare(jh_string_span(&item->name), name);
    if (order == 0)
      return item;
    if (order < 0)
      low = middle + 1;
    else
      high = middle;
  }
  return NULL;
}

static jb_json_span_t strip_one(jb_json_span_t item) {
  if (item.length >= 2 && memcmp(item.data + item.length - 2, "=1", 2) == 0)
    item.length -= 2;
  return item;
}

/* normalize_features of a descriptor array or list, without the =1. */
static bool normalized_symbols(jh_esp_t *e, const jb_vector_t *features,
                               jb_vector_t *out) {
  jb_vector_t normalized = {0};
  if (!esp_list_init(e, &normalized))
    return false;
  if (jh_board_normalize_features(features, &normalized, e->failure) == HAL_OK)
    for (size_t i = 0; i < jb_vector_size(&normalized) && esp_ok(e); ++i)
      (void)esp_push(e, out,
                     strip_one(jh_string_span(jh_list_at(&normalized, i))));
  jh_list_destroy(&normalized);
  return esp_ok(e);
}

static bool descriptor_strings(jh_esp_t *e, jb_json_tree_view_t array,
                               jb_vector_t *out) {
  for (size_t i = 0; i < jh_json_count(array) && esp_ok(e); ++i) {
    jb_json_span_t text = {"", 0};
    (void)jh_json_string(jh_json_item(array, i), &text);
    (void)esp_push(e, out, text);
  }
  return esp_ok(e);
}

/* all_features_for_target */
static bool all_features(jh_esp_t *e, const jh_board_descriptor_t *target,
                         jb_vector_t *features) {
  const jb_json_tree_view_t supported =
      jh_json_field(target->root, "supportedFeatures");
  if (jh_json_count(supported) == 0)
    return ESP_FAIL(
        e, jh_span("Target "), esp_repr(e, jh_string_span(&target->id)),
        jh_span(" declares no supportedFeatures for --all-features"));
  jb_vector_t raw = {0}, symbols = {0};
  if (esp_list_init(e, &raw) && esp_list_init(e, &symbols) &&
      descriptor_strings(e, supported, &raw) &&
      normalized_symbols(e, &raw, &symbols))
    for (size_t i = 0; i < jb_vector_size(&symbols) && esp_ok(e); ++i) {
      const jb_json_span_t symbol = jh_string_span(jh_list_at(&symbols, i));
      const jh_feature_t *item = feature(e, symbol);
      if (item == NULL)
        (void)ESP_FAIL(e, jh_span("Unknown supported feature: "), symbol);
      else if (!item->derived)
        (void)esp_push(e, features, symbol);
    }
  jh_list_destroy(&symbols);
  jh_list_destroy(&raw);
  return esp_ok(e);
}

static bool macro_defined(jb_json_tree_view_t macros, const char *name,
                          jb_json_tree_view_t *found) {
  for (size_t i = 0; i < jh_json_count(macros); ++i) {
    const jb_json_tree_view_t item = jh_json_item(macros, i);
    if (jh_span_equal(jh_build_descriptor_text(item, "name", NULL),
                      jh_span(name))) {
      if (found != NULL)
        *found = item;
      return true;
    }
  }
  return false;
}

/* collect_project_features: the build of hal_project_config.h with the
 * definitions (features are bare feature definitions), its requested
 * features into model->requested. header names the generated jh_hardware.h
 * of a device tree build, read first. */
static bool collect_features(jh_esp_t *e, const jh_board_descriptor_t *target,
                             const jb_vector_t *features,
                             const jb_vector_t *definitions,
                             const char *hardware_header,
                             jh_project_build_t *build) {
  jh_esp_model_t *m = &e->model;
  jb_vector_t normalized = {0}, required = {0}, spans = {0};
  jh_feature_resolution_t resolution;
  jh_feature_resolution_init(&resolution);
  jb_string_t context = {0};
  if (!esp_list_init(e, &normalized) || !esp_list_init(e, &required) ||
      !esp_storage(e, jb_vector_init(&spans, sizeof(jb_json_span_t),
                                     jb_heap_allocator())) ||
      !esp_storage(e, jb_string_init(&context, jb_heap_allocator())))
    goto done;
  for (size_t i = 0; i < jb_vector_size(definitions) && esp_ok(e); ++i) {
    const char *definition = normalize_definition(e, esp_at(definitions, i));
    (void)esp_push(e, &normalized, jh_span(definition));
  }
  if (!esp_ok(e) ||
      jh_board_validate_definitions(&normalized, e->failure) != HAL_OK)
    goto done;
  jb_vector_t normalized_features = {0};
  if (!esp_list_init(e, &normalized_features))
    goto done;
  (void)jh_board_normalize_features(features, &normalized_features, e->failure);
  for (size_t i = 0; i < jb_vector_size(&normalized) && esp_ok(e); ++i)
    (void)esp_push(e, &m->tree_definitions,
                   jh_string_span(jh_list_at(&normalized, i)));
  for (size_t i = 0; i < jb_vector_size(&normalized_features) && esp_ok(e);
       ++i) {
    const jb_json_span_t symbol =
        strip_one(jh_string_span(jh_list_at(&normalized_features, i)));
    if (!jh_list_contains(&normalized, symbol))
      (void)esp_push(e, &m->tree_definitions, symbol);
  }
  jh_list_destroy(&normalized_features);
  if (!descriptor_strings(e, jh_json_field(target->root, "requiredFeatures"),
                          &required))
    goto done;
  const char *header = esp_join(e, m->config_dir, "hal_project_config.h");
  const jh_project_build_options_t options = {
      header,
      hardware_header,
      jb_string_data(&target->id),
      ESP_TEXT(e,
               jh_build_descriptor_text(target->root, "hal", "targetSelector")),
      e->options->variant,
      &required,
      &m->tree_definitions};
  if (!esp_ok(e) ||
      jh_project_build_evaluate(&options, build, e->failure) != HAL_OK)
    goto done;
  /* resolve_build_features */
  for (size_t i = 0; i < jb_vector_size(&required) && esp_ok(e); ++i) {
    const jb_json_span_t item = jh_string_span(jh_list_at(&required, i));
    (void)esp_storage(e, jb_vector_append(&spans, &item, 1));
  }
  const jh_feature_target_t facts = {jh_string_span(&target->id),
                                     jb_vector_const_data(&spans),
                                     jb_vector_size(&spans)};
  if (!esp_storage(e, jh_join(&context, JH_PARTS(jh_span(header), jh_span(" ["),
                                                 jh_string_span(&build->label),
                                                 jh_span("]")))) ||
      jh_feature_resolve(&e->features, jb_vector_const_data(&build->requests),
                         jb_vector_size(&build->requests),
                         jh_string_span(&context), &facts, &resolution,
                         e->failure) != HAL_OK)
    goto done;
  if (jb_vector_size(&resolution.findings) != 0) {
    (void)ESP_FAIL(e, jh_span(esp_join_list(e, &resolution.findings, "\n")));
    goto done;
  }
  for (size_t i = 0; i < jb_vector_size(&resolution.requested) && esp_ok(e);
       ++i)
    (void)esp_push(e, &m->requested,
                   jh_string_span(jh_list_at(&resolution.requested, i)));
done:
  jb_string_destroy(&context);
  jh_feature_resolution_destroy(&resolution);
  jb_vector_destroy(&spans);
  jh_list_destroy(&required);
  jh_list_destroy(&normalized);
  return esp_ok(e);
}

/* validate_supported_features */
static bool supported_features(jh_esp_t *e,
                               const jh_board_descriptor_t *target) {
  jb_json_tree_view_t list = {0};
  if (!jh_json_member(target->root, "supportedFeatures", &list) ||
      jh_json_type(list) == JB_JSON_NULL)
    return esp_ok(e);
  jb_vector_t raw = {0}, supported = {0}, requested = {0}, resolved = {0};
  if (esp_list_init(e, &raw) && esp_list_init(e, &supported) &&
      esp_list_init(e, &requested) && esp_list_init(e, &resolved) &&
      descriptor_strings(e, list, &raw) &&
      normalized_symbols(e, &raw, &supported)) {
    const jb_vector_t *sources[] = {&e->model.requested, &e->model.resolved};
    jb_vector_t *outs[] = {&requested, &resolved};
    for (size_t s = 0; s < 2; ++s) {
      for (size_t i = 0; i < jb_vector_size(sources[s]) && esp_ok(e); ++i) {
        const jb_json_span_t item = jh_string_span(jh_list_at(sources[s], i));
        if (!jh_list_contains(&supported, item))
          (void)esp_push_unique(e, outs[s], item);
      }
      jh_list_sort(outs[s]);
    }
    if (esp_ok(e) &&
        (jb_vector_size(&requested) != 0 || jb_vector_size(&resolved) != 0)) {
      jb_vector_t details = {0};
      if (esp_list_init(e, &details)) {
        if (jb_vector_size(&requested) != 0)
          (void)esp_push(
              e, &details,
              jh_span(ESP_TEXT(e, jh_span("requested="),
                               jh_span(esp_join_list(e, &requested, ",")))));
        if (jb_vector_size(&resolved) != 0)
          (void)esp_push(
              e, &details,
              jh_span(ESP_TEXT(e, jh_span("resolved="),
                               jh_span(esp_join_list(e, &resolved, ",")))));
        const char *allowed = esp_join_list(e, &supported, ",");
        (void)ESP_FAIL(e, jh_span("[JH-CFG-UNSUPPORTED] target "),
                       jh_string_span(&target->id), jh_span(" supports only "),
                       jh_span(allowed[0] != '\0' ? allowed : "none"),
                       jh_span("; "),
                       jh_span(esp_join_list(e, &details, "; ")));
      }
      jh_list_destroy(&details);
    }
  }
  jh_list_destroy(&resolved);
  jh_list_destroy(&requested);
  jh_list_destroy(&supported);
  jh_list_destroy(&raw);
  return esp_ok(e);
}

/* resolve_component_build_inputs */
static bool component_inputs(jh_esp_t *e) {
  jh_esp_model_t *m = &e->model;
  jb_vector_t feature_sources = {0}, portable = {0}, dependencies = {0},
              keys = {0};
  if (!esp_list_init(e, &feature_sources) || !esp_list_init(e, &portable) ||
      !esp_list_init(e, &dependencies) || !esp_list_init(e, &keys))
    goto done;
  for (size_t i = 0; i < jb_vector_size(&m->resolved) && esp_ok(e); ++i) {
    const jb_json_span_t name = jh_string_span(jh_list_at(&m->resolved, i));
    const jh_feature_t *item = feature(e, name);
    if (item == NULL) {
      (void)ESP_FAIL(e, jh_span("Unknown resolved feature: "), name);
      break;
    }
    const jb_vector_t *from[] = {&item->feature_sources,
                                 &item->portable_sources, &item->dependencies};
    jb_vector_t *to[] = {&feature_sources, &portable, &dependencies};
    for (size_t l = 0; l < COUNTOF(from); ++l)
      for (size_t j = 0; j < jb_vector_size(from[l]) && esp_ok(e); ++j)
        (void)esp_push_unique(e, to[l], jh_string_span(jh_list_at(from[l], j)));
  }
  jh_list_sort(&feature_sources);
  jh_list_sort(&portable);
  jh_list_sort(&dependencies);
  (void)table_strings(e, esp_table(e, "baseSources"), &m->integration_sources,
                      true);
  for (size_t i = 0; i < jb_vector_size(&feature_sources) && esp_ok(e); ++i)
    (void)esp_push_unique(e, &m->integration_sources,
                          jh_string_span(jh_list_at(&feature_sources, i)));
  for (size_t i = 0; i < jb_vector_size(&portable) && esp_ok(e); ++i)
    (void)esp_push_unique(e, &m->integration_sources,
                          jh_string_span(jh_list_at(&portable, i)));
  (void)table_strings(e, esp_table(e, "basePrivateDependencies"),
                      &m->private_dependencies, true);
  const jb_json_tree_view_t target_sources = esp_table(e, "targetSources");
  const jb_json_tree_view_t feature_dependencies =
      esp_table(e, "featureDependencies");
  (void)table_keys(e, target_sources, &keys);
  for (size_t i = 0; i < jb_vector_size(&keys) && esp_ok(e); ++i) {
    const char *name = esp_at(&keys, i);
    if (!jh_list_contains(&m->resolved, jh_span(name)))
      continue;
    (void)table_strings(e, jh_json_field(target_sources, name),
                        &m->integration_sources, true);
    (void)table_strings(e, jh_json_field(feature_dependencies, name),
                        &m->private_dependencies, true);
  }
  const jb_json_tree_view_t managed = esp_table(e, "managedDependencies");
  for (size_t i = 0; i < jb_vector_size(&dependencies) && esp_ok(e); ++i) {
    const char *name = esp_at(&dependencies, i);
    jb_json_tree_view_t components = {0};
    if (!jh_json_member(managed, name, &components)) {
      (void)ESP_FAIL(e, jh_span("ESP-IDF does not support managed dependency "),
                     esp_repr(e, jh_span(name)));
      break;
    }
    (void)table_strings(e, components, &m->private_dependencies, true);
  }
  (void)table_strings(e, esp_table(e, "publicDependencies"),
                      &m->component_dependencies, false);
done:
  jh_list_destroy(&keys);
  jh_list_destroy(&dependencies);
  jh_list_destroy(&portable);
  jh_list_destroy(&feature_sources);
  return esp_ok(e);
}

/* resolve_project_inputs */
static bool project_inputs(jh_esp_t *e, const jb_vector_t *requested,
                           const char *kind, bool directory, jb_vector_t *out) {
  const char *project_dir = e->model.project_dir;
  for (size_t i = 0;
       requested != NULL && i < jb_vector_size(requested) && esp_ok(e); ++i) {
    const char *candidate = esp_expand_user(e, esp_at(requested, i));
    const char *path = esp_resolve(e,
                                   esp_absolute(candidate)
                                       ? candidate
                                       : esp_join(e, project_dir, candidate),
                                   e->options->base);
    if (!esp_ok(e))
      break;
    if (!(directory ? esp_is_dir(path) : esp_is_file(path)))
      return ESP_FAIL(e, jh_span("Project "), jh_span(kind),
                      jh_span(" does not exist: "), jh_span(path));
    (void)esp_push_unique(e, out, jh_span(path));
  }
  return esp_ok(e);
}

/* The jh_hardware.h of a device tree build written for the project
 * configuration reader, which takes a path. */
static bool evaluate(jh_esp_t *e, const jh_board_descriptor_t *target,
                     const jb_vector_t *features,
                     const jb_vector_t *definitions,
                     jh_project_build_t *build) {
  const char *header = "";
  jb_temp_dir_t *scratch = NULL;
  if (e->model.device_tree) {
    if (jh_process_scratch(&scratch, e->failure) != HAL_OK)
      return false;
    header = esp_join(e, jb_temp_dir_path(scratch), "jh_hardware.h");
    bool changed = false;
    if (esp_ok(e))
      (void)esp_storage(e, jb_file_write_atomic(header, e->model.header,
                                                strlen(e->model.header), false,
                                                &changed));
  }
  if (esp_ok(e))
    (void)collect_features(e, target, features, definitions, header, build);
  const hal_status_t removed = jb_temp_dir_remove(&scratch);
  (void)removed;
  return esp_ok(e);
}

/* The device tree of the configuration directory, resolved for target and
 * the requested assembly with the board it builds. */
static bool resolve_tree(jh_esp_t *e, const char *path, const char *target,
                         jb_vector_t *compiler_definitions) {
  jh_esp_model_t *m = &e->model;
  if (jh_hardware_registry_load(&e->hardware, e->repo_root, REGISTRY_LIMIT,
                                e->failure) != HAL_OK)
    return false;
  e->hardware_loaded = true;
  jh_hardware_t hardware = {0};
  jb_string_t header = {0}, document = {0}, board = {0};
  jb_json_tree_t *board_tree = NULL;
  if (esp_storage(e, jb_string_init(&header, jb_heap_allocator())) &&
      esp_storage(e, jb_string_init(&document, jb_heap_allocator())) &&
      esp_storage(e, jb_string_init(&board, jb_heap_allocator())) &&
      jh_hardware_load(&hardware, &e->hardware, path, e->failure) == HAL_OK &&
      jh_hardware_resolve(&hardware, target,
                          e->options->assembly[0] != '\0' ? e->options->assembly
                                                          : NULL,
                          e->failure) == HAL_OK &&
      jh_hardware_header(&hardware, &header, e->failure) == HAL_OK &&
      jh_hardware_document(&hardware, &document, e->failure) == HAL_OK &&
      jh_hardware_board_json(&hardware, &board, e->failure) == HAL_OK) {
    const jb_json_tree_view_t selection =
        jh_json_field(jh_hardware_model(&hardware), "selection");
    m->board = ESP_TEXT(e, jh_build_descriptor_text(selection, "board", NULL));
    m->assembly =
        ESP_TEXT(e, jh_build_descriptor_text(selection, "assembly", NULL));
    m->header = ESP_TEXT(e, jh_string_span(&header));
    m->document = ESP_TEXT(e, jh_string_span(&document));
    jb_json_tree_view_t root = {0};
    if (esp_ok(e) &&
        esp_storage(
            e, jh_json_tree_from_text(jh_string_span(&board), &board_tree)) &&
        esp_storage(e, jb_json_tree_root(board_tree, &root)))
      (void)descriptor_strings(e, jh_json_field(root, "compilerDefinitions"),
                               compiler_definitions);
  }
  jb_json_tree_destroy(board_tree);
  jb_string_destroy(&board);
  jb_string_destroy(&document);
  jb_string_destroy(&header);
  jh_hardware_destroy(&hardware);
  return esp_ok(e);
}

static int compare_texts(const void *left, const void *right) {
  return strcmp(jb_string_data(left), jb_string_data(right));
}

bool esp_resolve_model(jh_esp_t *e, const char *project_dir,
                       const char *project_name) {
  const jh_esp_options_t *o = e->options;
  jh_esp_model_t *m = &e->model;
  m->project_dir = project_dir;
  m->project_name = project_name;
  m->config_dir =
      o->project_config[0] != '\0'
          ? esp_resolve(e, esp_expand_user(e, o->project_config), o->base)
          : project_dir;
  if (esp_ok(e) && !esp_is_dir(m->config_dir))
    return ESP_FAIL(e, jh_span("Project config directory does not exist: "),
                    jh_span(m->config_dir));
  const char *config_root = esp_join(e, e->repo_root, "config");
  const char *boards_root = esp_join(e, e->repo_root, "boards");
  if (!esp_ok(e) ||
      jh_feature_registry_load(&e->features, config_root, REGISTRY_LIMIT,
                               e->failure) != HAL_OK ||
      jh_board_registry_load_with_features(&e->boards, e->repo_root,
                                           boards_root, REGISTRY_LIMIT,
                                           &e->features, e->failure) != HAL_OK)
    return false;
  m->target = o->target[0] != '\0' ? o->target : "esp32s3";
  const jh_board_descriptor_t *target =
      jh_board_registry_find(&e->boards.targets, jh_span(m->target));
  if (target == NULL)
    return ESP_FAIL(e, jh_span("Unknown JaszczurHAL target: "),
                    esp_repr(e, jh_span(m->target)));
  m->target_descriptor = target;
  const char *tree_path = esp_join(e, m->config_dir, "device_tree.json");
  jb_vector_t compiler_definitions = {0}, features = {0}, definitions = {0};
  jh_project_build_t build;
  jh_project_build_init(&build);
  if (!esp_list_init(e, &compiler_definitions) ||
      !esp_list_init(e, &features) || !esp_list_init(e, &definitions))
    goto done;
  if (esp_is_file(tree_path)) {
    if (o->board[0] != '\0') {
      (void)ESP_FAIL(e, jh_span("[JH-HW-BOARD] "), jh_span(tree_path),
                     jh_span(" selects the board through its assemblies; use "
                             "--assembly instead of --board"));
      goto done;
    }
    m->device_tree = true;
    if (!resolve_tree(e, tree_path, m->target, &compiler_definitions))
      goto done;
  } else {
    if (o->assembly[0] != '\0') {
      (void)ESP_FAIL(e, jh_span("[JH-HW-ASSEMBLY] --assembly needs "),
                     jh_span(tree_path));
      goto done;
    }
    m->board = o->board[0] != '\0'
                   ? o->board
                   : ESP_TEXT(e, jh_build_descriptor_text(
                                     target->root, "defaultBoard", NULL));
  }
  const jh_board_descriptor_t *board =
      jh_board_registry_find(&e->boards.boards, jh_span(m->board));
  if (esp_ok(e) && board == NULL) {
    (void)ESP_FAIL(e, jh_span("Unknown JaszczurHAL board: "),
                   esp_repr(e, jh_span(m->board)));
    goto done;
  }
  if (!esp_ok(e))
    goto done;
  m->board_descriptor = board;
  bool compatible = false;
  const jb_json_tree_view_t targets =
      jh_json_field(board->root, "compatibleTargets");
  for (size_t i = 0; i < jh_json_count(targets); ++i)
    compatible =
        compatible || jh_span_equal(jh_build_descriptor_text(
                                        jh_json_item(targets, i), NULL, NULL),
                                    jh_span(m->target));
  if (!compatible) {
    (void)ESP_FAIL(e, jh_span("Board "), esp_repr(e, jh_span(m->board)),
                   jh_span(" is not compatible with "),
                   esp_repr(e, jh_span(m->target)));
    goto done;
  }
  if (!jh_span_equal(
          jh_build_descriptor_text(target->root, "build", "provider"),
          jh_span("esp-idf")) ||
      !jh_span_equal(jh_build_descriptor_text(board->root, "build", "provider"),
                     jh_span("esp-idf"))) {
    (void)ESP_FAIL(e, jh_span("Target/board "), jh_span(m->target),
                   jh_span(":"), jh_span(m->board),
                   jh_span(" does not use ESP-IDF"));
    goto done;
  }
  m->idf_target =
      ESP_TEXT(e, jh_build_descriptor_text(target->root, "build", "idfTarget"));
  if (esp_ok(e) && m->idf_target[0] == '\0') {
    (void)ESP_FAIL(e, jh_span("Target "), esp_repr(e, jh_span(m->target)),
                   jh_span(" has no ESP-IDF target mapping"));
    goto done;
  }
  if (!project_sources(e, project_dir))
    goto done;
  for (size_t i = 0; i < jb_vector_size(o->defines) && esp_ok(e); ++i)
    (void)esp_push(e, &definitions, jh_string_span(jh_list_at(o->defines, i)));
  if (o->all_features) {
    if (!all_features(e, target, &features))
      goto done;
    bool display = false;
    for (size_t i = 0; i < jb_vector_size(&definitions) && esp_ok(e); ++i) {
      const char *definition = normalize_definition(e, esp_at(&definitions, i));
      display = display || strncmp(definition, "HAL_DISPLAY_", 12) == 0;
    }
    /* HAL_ENABLE_TFT needs one concrete facade selection even though every
     * TFT driver is enabled; mirror jh_all_features_for_target. */
    if (esp_ok(e) && jh_list_contains(&features, jh_span("HAL_ENABLE_TFT")) &&
        !display)
      (void)esp_push(e, &definitions, jh_span("HAL_DISPLAY_ILI9341"));
  }
  if (!esp_ok(e) || !evaluate(e, target, &features, &definitions, &build))
    goto done;
  {
    jb_vector_t normalized = {0};
    jh_feature_resolution_t resolution;
    jh_feature_resolution_init(&resolution);
    if (esp_list_init(e, &normalized) &&
        jh_board_normalize_features(&m->requested, &normalized, e->failure) ==
            HAL_OK &&
        jh_board_resolve_features(&e->features, target->root, &normalized,
                                  &resolution, e->failure) == HAL_OK)
      for (size_t i = 0; i < jb_vector_size(&resolution.resolved) && esp_ok(e);
           ++i)
        (void)esp_push(e, &m->resolved,
                       jh_string_span(jh_list_at(&resolution.resolved, i)));
    jh_feature_resolution_destroy(&resolution);
    jh_list_destroy(&normalized);
  }
  if (!esp_ok(e) || !supported_features(e, target) || !component_inputs(e))
    goto done;
  /* Classic serial uses UART even when the optional HAL UART API is
   * disabled. */
  if (strcmp(m->target, "esp32") == 0)
    (void)esp_push_unique(e, &m->private_dependencies,
                          jh_span("esp_driver_uart"));
  /* The header defines its own features; a required feature it leaves out
   * reaches the compiler as a definition, like the variant's definitions. */
  const jb_json_tree_view_t macros = jh_json_field(build.config_root, "macros");
  jb_vector_t *defs = &m->compile_definitions;
  (void)esp_push_unique(
      e, defs, jh_build_descriptor_text(target->root, "hal", "targetSelector"));
  for (size_t i = 0; i < jb_vector_size(&build.definitions) && esp_ok(e); ++i)
    (void)esp_push_unique(e, defs,
                          jh_string_span(jh_list_at(&build.definitions, i)));
  const jb_json_tree_view_t required =
      jh_json_field(target->root, "requiredFeatures");
  for (size_t i = 0; i < jh_json_count(required) && esp_ok(e); ++i) {
    const jb_json_span_t symbol = strip_one(
        jh_build_descriptor_text(jh_json_item(required, i), NULL, NULL));
    bool header_feature = false;
    for (size_t j = 0; j < jh_json_count(macros) && !header_feature; ++j) {
      const jb_json_tree_view_t item = jh_json_item(macros, j);
      header_feature =
          jh_span_equal(jh_build_descriptor_text(item, "name", NULL), symbol) &&
          !jh_span_equal(jh_build_descriptor_text(item, "source", NULL),
                         jh_span("predefined"));
    }
    if (!header_feature)
      (void)esp_push_unique(e, defs, symbol);
  }
  if (m->device_tree) {
    for (size_t i = 0; i < jb_vector_size(&compiler_definitions) && esp_ok(e);
         ++i)
      (void)esp_push_unique(
          e, defs, jh_string_span(jh_list_at(&compiler_definitions, i)));
  } else {
    jb_vector_t board_defs = {0};
    if (esp_list_init(e, &board_defs) &&
        esp_storage(e, jh_board_compile_definitions(target->root, board->root,
                                                    &board_defs)))
      for (size_t i = 0; i < jb_vector_size(&board_defs) && esp_ok(e); ++i)
        (void)esp_push_unique(e, defs,
                              jh_string_span(jh_list_at(&board_defs, i)));
    jh_list_destroy(&board_defs);
  }
  if (!macro_defined(macros, "HAL_PROVIDE_APP_ENTRY", NULL))
    (void)esp_push_unique(e, defs, jh_span("HAL_PROVIDE_APP_ENTRY"));
  jh_list_sort(defs);
  if (!project_inputs(e, o->include_dirs, "include directory", true,
                      &m->extra_include_dirs) ||
      !project_inputs(e, o->link_libraries, "link library", false,
                      &m->link_libraries))
    goto done;
  {
    jb_vector_t include = {0};
    if (esp_list_init(e, &include)) {
      (void)esp_push_unique(e, &include, jh_span(esp_posix(e, project_dir)));
      (void)esp_push_unique(e, &include, jh_span(esp_posix(e, m->config_dir)));
      for (size_t i = 0; i < jb_vector_size(&m->project_sources) && esp_ok(e);
           ++i)
        (void)esp_push_unique(
            e, &include,
            jh_span(
                esp_posix(e, esp_parent(e, esp_at(&m->project_sources, i)))));
      if (jb_vector_size(&include) > 1)
        qsort(jb_vector_data(&include), jb_vector_size(&include),
              sizeof(jb_string_t), compare_texts);
      for (size_t i = 0; i < jb_vector_size(&include) && esp_ok(e); ++i)
        (void)esp_push(e, &m->project_include_dirs,
                       jh_string_span(jh_list_at(&include, i)));
    }
    jh_list_destroy(&include);
  }
  {
    const jb_json_tree_view_t frameworks = esp_table(e, "managedFrameworks");
    jb_vector_t keys = {0};
    if (esp_list_init(e, &keys) && table_keys(e, frameworks, &keys))
      for (size_t i = 0; i < jb_vector_size(&keys) && esp_ok(e); ++i) {
        const char *name = esp_at(&keys, i);
        if (!jh_list_contains(&m->resolved, jh_span(name)))
          continue;
        const jb_json_tree_view_t entry = jh_json_field(frameworks, name);
        (void)esp_push_unique(
            e, &m->managed_frameworks,
            jh_build_descriptor_text(entry, "component", NULL));
        (void)table_strings(e, jh_json_field(entry, "includeDirs"),
                            &m->component_include_dirs, true);
      }
    jh_list_destroy(&keys);
  }
  jb_json_tree_view_t ram = {0};
  if (macro_defined(macros, "HAL_RAM_CODE_SOURCES", &ram))
    m->ram_code_sources =
        ESP_TEXT(e, jh_build_descriptor_text(ram, "body", NULL));
  m->variant = o->variant[0] != '\0' ? o->variant : NULL;
  m->build_key = m->device_tree ? m->assembly : m->board;
done:
  jh_project_build_destroy(&build);
  jh_list_destroy(&definitions);
  jh_list_destroy(&features);
  jh_list_destroy(&compiler_definitions);
  return esp_ok(e);
}

/* resolve_build_dir */
bool esp_resolve_build_dir(jh_esp_t *e, const char *project_dir) {
  const jh_esp_options_t *o = e->options;
  const char *project_root =
      esp_resolve(e, esp_join(e, project_dir, ".build"), o->base);
  const char *repository_root =
      esp_resolve(e, esp_join(e, e->repo_root, ".build"), o->base);
  const char *candidate =
      o->output[0] != '\0'
          ? esp_expand_user(e, o->output)
          : esp_join(e,
                     esp_join(e, esp_join(e, project_root, "esp-idf"),
                              e->model.target),
                     e->model.build_key);
  if (!esp_absolute(candidate))
    candidate = esp_join(e, project_dir, candidate);
  const char *resolved = esp_resolve(e, candidate, o->base);
  if (!esp_ok(e))
    return false;
  const char *roots[] = {project_root, repository_root};
  bool equal = false, inside = false;
  for (size_t i = 0; i < COUNTOF(roots); ++i) {
    const char *relative = esp_relative(e, resolved, roots[i]);
    equal = equal || (relative != NULL && strcmp(relative, ".") == 0);
    inside = inside || relative != NULL;
  }
  if (equal || !inside)
    return ESP_FAIL(e,
                    jh_span("Build directory must be below a managed .build "
                            "root ("),
                    jh_span(project_root), jh_span(", "),
                    jh_span(repository_root), jh_span("): "),
                    jh_span(resolved));
  e->build_dir = resolved;
  return true;
}

